# Emits our own "input prep" kernel (run once per app frame): it turns the two colour frames into the flow net's
# two small input textures, in the pack's kernel interface (p_desc, 48-byte slots p_s0, p_s1, p_s32, p_s33, the
# constant buffer by value in p_cb0) so it replaces the translated module in a pack as it is. Grid: 8 x 8 threads per
# block, one thread per 4 x 4 block of source pixels.
#
# Constant buffer (10 dwords used, 3 registers): r0 = rectangle (x, y, w, h) of frame A (slot 0), r1 = rectangle of
# frame B (slot 1), r2.xy = offset taken off each thread's block origin. A thread whose index is at or past (r0.z, r0.w)
# does no work. Slots: 0 / 1 = the two frames (textures, read as float4 through the texture object at +40 of the
# slot), 33 = quarter-size output, 32 = sixteenth-size output; both outputs are 2-byte texels (two int8), written
# through the slot's base address (+0) with its size (+16 w, +20 h, +24 d), texel size (+28) and row pitch (+36).
#
# What it computes, per thread (tx, ty), for each frame:
#   origin  = rect.xy + (4 tx - off.x, 4 ty - off.y)
#   luma(p) = 255 * (0.2126 r + 0.7152 g + 0.0722 b) of the saturated texel (first product plain, then two
#             fused multiply-adds in the channel order r, g, b)
#   sum     = running sum over the 16 texels of the 4 x 4 block, column by column (x outer, y inner), starting at 0:
#             sum = fma(luma, 255, sum). A texel outside the frame's rectangle (unsigned compare of the absolute
#             coordinate against rect.x / rect.x + rect.w, same for y) is not read and adds nothing
#   level 1 = clamp(trunc(sum / 16 - 128), -128, 127) per frame -> (frame A, frame B) int8 pair at (tx, ty) of slot 33
# Then the 8 x 8 sums of a block go through shared memory, and the threads with local index (0..1, 0..1) each add
# a 4 x 4 square of them (row by row, left to right, plain adds) and write
#   level 2 = clamp(trunc(sum / 256 - 128), -128, 127) per frame -> int8 pair at (2 bx + lx, 2 by + ly) of slot 32.
# Every ordering above matters: the results are bit-exact against the module this replaces.
#
# Usage: python gen_prep_ptx.py <out.ptx>
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("out")
a = ap.parse_args()

LUMA = ("0f3E59B3D0", "0f3F371759", "0f3D93DD98")        # 0.2126, 0.7152, 0.0722 as float32
F255 = "0f437F0000"
INV16, INV256, M128 = "0f3D800000", "0f3B800000", "0fC3000000"

L = []


def w(s=""):
    L.append(s)


w("// GENERATED by tools/kernels/gen_prep_ptx.py - do not edit by hand.")
w("// numthreads 8 x 8 x 1; ftz")
w(".version 7.0")
w(".target sm_75")
w(".address_size 64")
w("")
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
w("    .param .align 16 .b8 p_s0[48],")
w("    .param .align 16 .b8 p_s1[48],")
w("    .param .align 16 .b8 p_s32[48],")
w("    .param .align 16 .b8 p_s33[48],")
w("    .param .align 16 .b8 p_cb0[48]")
w(") .reqntid 8, 8, 1")
w("{")
w("    .shared .align 16 .b32 smA[64];")
w("    .shared .align 16 .b32 smB[64];")
w("    .reg .pred %pt, %live, %ox, %pl, %oa<16>, %ob<16>;")
w("    .reg .b32 %va<64>, %vb<64>;")
w("    .reg .b32 %tx, %ty, %lx, %ly, %t0, %t1, %t2, %t3, %bx, %by, %x0, %y0, %xx, %yy, %xe, %ye;")
w("    .reg .b32 %ra_x, %ra_y, %ra_w, %ra_h, %rb_x, %rb_y, %rb_w, %rb_h, %off_x, %off_y;")
w("    .reg .b32 %c0, %c1, %c2, %l, %accA, %accB, %fq, %ia, %ib, %pk;")
w("    .reg .b32 %m, %n, %sA, %sB, %shA, %shB, %ox2, %oy2, %pitch, %esz, %wd, %ht, %dp;")
w("    .reg .b64 %q0, %q1, %base, %addr64;")
w("")
w("    mov.u32 %t0, %ctaid.x;")
w("    mov.u32 %t1, %ntid.x;")
w("    mov.u32 %lx, %tid.x;")
w("    mad.lo.s32 %tx, %t0, %t1, %lx;")
w("    mov.u32 %t0, %ctaid.y;")
w("    mov.u32 %t1, %ntid.y;")
w("    mov.u32 %ly, %tid.y;")
w("    mad.lo.s32 %ty, %t0, %t1, %ly;")
w("    ld.param.v4.b32 {%ra_x, %ra_y, %ra_w, %ra_h}, [p_cb0+0];")
w("    ld.param.v4.b32 {%rb_x, %rb_y, %rb_w, %rb_h}, [p_cb0+16];")
w("    ld.param.v4.b32 {%off_x, %off_y, %t2, %t3}, [p_cb0+32];")
w("    setp.lo.u32 %live, %tx, %ra_w;")
w("    setp.lo.and.u32 %live, %ty, %ra_h, %live;")
w("    mov.b32 %accA, 0;")
w("    mov.b32 %accB, 0;")
w("    @!%live bra STAGE2;")
w("    shl.b32 %bx, %tx, 2;")
w("    shl.b32 %by, %ty, 2;")
w("    sub.s32 %bx, %bx, %off_x;")
w("    sub.s32 %by, %by, %off_y;")


def fetch(slot, rx, ry, rw, rh, v, o):
    """Reads the 16 texels of the thread's block of one frame into %<v><tap*4 + channel> (taps column by column), and
    sets %<o><tap> where the texel lies outside the frame's rectangle (it is then not read). All reads are issued
    before any arithmetic so they are in flight together."""
    w(f"    // frame in slot {slot}: the 4 x 4 block")
    w(f"    ld.param.u64 %q{slot}, [p_s{slot}+40];")
    w(f"    add.s32 %x0, {rx}, %bx;")
    w(f"    add.s32 %y0, {ry}, %by;")
    w(f"    add.s32 %xe, {rx}, {rw};")
    w(f"    add.s32 %ye, {ry}, {rh};")
    for dx in range(4):
        w(f"    add.s32 %xx, %x0, {dx};")
        w(f"    setp.hs.u32 %ox, %xx, %xe;")
        w(f"    setp.lo.or.u32 %ox, %xx, {rx}, %ox;")
        for dy in range(4):
            t = dx * 4 + dy
            w(f"    add.s32 %yy, %y0, {dy};")
            w(f"    setp.hs.or.u32 %{o}{t}, %yy, %ye, %ox;")
            w(f"    setp.lo.or.u32 %{o}{t}, %yy, {ry}, %{o}{t};")
            w(f"    @!%{o}{t} tex.2d.v4.f32.s32 {{%{v}{4 * t}, %{v}{4 * t + 1}, %{v}{4 * t + 2}, %{v}{4 * t + 3}}}, "
              f"[%q{slot}, {{%xx, %yy}}];")


def accumulate(v, o, acc):
    """acc = running sum, tap by tap, of 255 * luma(texel) over the taps that were read (fused multiply-add)."""
    for t in range(16):
        w(f"    cvt.ftz.sat.f32.f32 %c0, %{v}{4 * t};")
        w(f"    cvt.ftz.sat.f32.f32 %c1, %{v}{4 * t + 1};")
        w(f"    cvt.ftz.sat.f32.f32 %c2, %{v}{4 * t + 2};")
        w(f"    mul.rn.ftz.f32 %l, %c0, {LUMA[0]};")
        w(f"    fma.rn.ftz.f32 %l, %c1, {LUMA[1]}, %l;")
        w(f"    fma.rn.ftz.f32 %l, %c2, {LUMA[2]}, %l;")
        w(f"    @!%{o}{t} fma.rn.ftz.f32 {acc}, %l, {F255}, {acc};")


fetch(0, "%ra_x", "%ra_y", "%ra_w", "%ra_h", "va", "oa")
fetch(1, "%rb_x", "%rb_y", "%rb_w", "%rb_h", "vb", "ob")
accumulate("va", "oa", "%accA")
accumulate("vb", "ob", "%accB")


def level(acc, scale, out):
    """out = clamp(trunc(acc * scale - 128), -128, 127) as an s32."""
    w(f"    fma.rn.ftz.f32 %fq, {acc}, {scale}, {M128};")
    w(f"    cvt.rzi.ftz.s32.f32 {out}, %fq;")
    w(f"    max.s32 {out}, {out}, -128;")
    w(f"    min.s32 {out}, {out}, 127;")


def store_pair(slot, px, py, ia, ib, pred):
    """Two int8 (ia low, ib high) as one 2-byte texel at (px, py) of slot `slot`, if inside the slot's size."""
    w(f"    ld.param.u64 %base, [p_s{slot}+0];")
    w(f"    ld.param.u32 %wd, [p_s{slot}+16];")
    w(f"    ld.param.u32 %ht, [p_s{slot}+20];")
    w(f"    ld.param.u32 %dp, [p_s{slot}+24];")
    w(f"    ld.param.u32 %esz, [p_s{slot}+28];")
    w(f"    ld.param.u32 %pitch, [p_s{slot}+36];")
    w(f"    setp.lo.u32 %pt, {px}, %wd;")
    w(f"    setp.lo.and.u32 %pt, {py}, %ht, %pt;")
    w(f"    setp.lo.and.u32 %pt, 0, %dp, %pt;")
    w(f"    and.pred %pt, %pt, {pred};")
    w(f"    mul.lo.s32 %t2, {py}, %pitch;")
    w(f"    mad.lo.s32 %t2, {px}, %esz, %t2;")
    w(f"    cvt.u64.u32 %addr64, %t2;")
    w(f"    add.s64 %addr64, %base, %addr64;")
    w(f"    and.b32 %ia, {ia}, 255;")
    w(f"    and.b32 %ib, {ib}, 255;")
    w(f"    shl.b32 %ib, %ib, 8;")
    w(f"    or.b32 %pk, %ia, %ib;")
    w(f"    @%pt st.global.b16 [%addr64], %pk;")


w("    // level 1: mean of the block, one texel per thread")
level("%accA", INV16, "%ia")
level("%accB", INV16, "%ib")
store_pair(33, "%tx", "%ty", "%ia", "%ib", "%live")
w("STAGE2:")
w("    // level 2: the 8 x 8 sums of the block through shared memory")
w("    shl.b32 %m, %ly, 3;")
w("    add.s32 %m, %m, %lx;")
w("    shl.b32 %m, %m, 2;")
w("    mov.u32 %shA, smA;")
w("    mov.u32 %shB, smB;")
w("    add.s32 %t0, %shA, %m;")
w("    add.s32 %t1, %shB, %m;")
w("    st.shared.f32 [%t0], %accA;")
w("    st.shared.f32 [%t1], %accB;")
w("    bar.sync 0;")
w("    or.b32 %t0, %lx, %ly;")
w("    setp.lo.u32 %pl, %t0, 2;")
w("    @!%pl bra DONE;")
w("    shl.b32 %m, %ly, 5;           // 4 ly rows of 8 sums")
w("    shl.b32 %n, %lx, 2;           // 4 lx sums")
w("    add.s32 %m, %m, %n;")
w("    shl.b32 %m, %m, 2;            // bytes")
w("    add.s32 %sA, %shA, %m;")
w("    add.s32 %sB, %shB, %m;")
for name, base, acc in (("A", "%sA", "%accA"), ("B", "%sB", "%accB")):
    first = True
    for j in range(4):
        for i in range(4):
            off = (j * 8 + i) * 4
            if first:
                w(f"    ld.shared.f32 {acc}, [{base}+{off}];")
                first = False
            else:
                w(f"    ld.shared.f32 %fq, [{base}+{off}];")
                w(f"    add.rn.ftz.f32 {acc}, {acc}, %fq;")
level("%accA", INV256, "%ia")
level("%accB", INV256, "%ib")
w("    mov.u32 %t0, %ctaid.x;")
w("    mov.u32 %t1, %ctaid.y;")
w("    shl.b32 %ox2, %t0, 1;")
w("    shl.b32 %oy2, %t1, 1;")
w("    add.s32 %ox2, %ox2, %lx;")
w("    add.s32 %oy2, %oy2, %ly;")
store_pair(32, "%ox2", "%oy2", "%ia", "%ib", "%live")
w("DONE:")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
