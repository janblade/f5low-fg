def smooth_mask(v, scale):
    """s = saturate(v * scale); returns (s, s*s, fma(-s, 2, 3))"""
    m = r()
    mul(m, v, scale)
    s = r()
    ptx("cvt.ftz.sat.f32.f32", s, m)
    sq = r()
    mul(sq, s, s)
    ns = r()
    ptx("neg.ftz.f32", ns, s)
    t = r()
    fma(t, ns, TWO, THREE)
    return s, sq, t


def ui_over(dst, ui, base_col, alpha):
    """dst = base_col * (1 - alpha) + (ui rgb [* alpha when straight])"""
    o = r()
    sub(o, ONE, alpha)
    addend = ui
    if not PREMUL:
        addend = rs(3)
        for c in range(3):
            mul(addend[c], ui[c], alpha)
    for c in range(3):
        fma(dst[c], o, base_col[c], addend[c])
    return o, addend


def dist_mask(p, q):
    """k = 1 - smoothstep(20 * |p - q|)"""
    d = rs(3)
    for c in range(3):
        sub(d[c], p[c], q[c])
    sq1 = r()
    mul(sq1, d[1], d[1])
    s01 = r()
    fma(s01, d[0], d[0], sq1)
    s012 = r()
    fma(s012, d[2], d[2], s01)
    ln = r()
    ptx("sqrt.approx.ftz.f32", ln, s012)
    s, sq, t = smooth_mask(ln, "0f41A00000")
    nsq = r()
    ptx("neg.ftz.f32", nsq, sq)
    k = r()
    fma(k, nsq, t, ONE)
    return k


