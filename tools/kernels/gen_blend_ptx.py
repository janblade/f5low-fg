L = []
NREG = [0]
NQ = [0]


def w(s=""):
    L.append(s)


def r():
    """A fresh 32-bit register."""
    NREG[0] += 1
    return f"%r{NREG[0]}"


def rs(n):
    return [r() for _ in range(n)]


def ptx(op, *args):
    w(f"    {op} {', '.join(str(g) for g in args)};")


def handle(slot):
    """A fresh 64-bit register holding the texture object of a slot (own register for every use: the D3D12 rewrite
    finds the sampler of a fetch through it)."""
    NQ[0] += 1
    q = f"%q{NQ[0]}"
    ptx("ld.param.u64", q, f"[p_s{slot}+40]")
    return q


def fetch(slot, x, y):
    """Integer-coordinate fetch of the texel (x, y) of a texture slot -> 4 registers."""
    d = rs(4)
    q = handle(slot)
    w(f"    tex.2d.v4.f32.s32 {{{', '.join(d)}}}, [{q}, {{{x}, {y}}}];")
    return d


def fma(d, x, y, z):
    ptx("fma.rn.ftz.f32", d, x, y, z)


def sub(d, x, y):
    ptx("sub.rn.ftz.f32", d, x, y)


def mul(d, x, y):
    ptx("mul.rn.ftz.f32", d, x, y)


