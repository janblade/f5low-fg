# Emits our own "blend" kernel (k31): the last pass of every generated frame. It turns the U-Net's 16 int8 channels
# into five blend weights, mixes the reconstructed images with them, composites the game's UI over the result and
# writes the finished pixel into the (redirected) output of the generated frame. It replaces the translated module
# in a pack as it is: same kernel interface (p_desc, 48-byte slots, the constant buffer by value in p_cb0), 8 x 8
# threads per block, one thread per output pixel.
#
# Usage: python gen_blend_ptx.py <out.ptx> [--hdr] [--premul 0|1]
#   --hdr      the HDR10 pack: the reconstructed images are four textures (slots 1..4) and the output is R10G10B10A2.
#              Default (SDR): three textures (slots 1..3) whose alpha channels carry a fourth image, output R8G8B8A8.
#   --premul   1 (default): the UI texture (slot 9) is premultiplied, 0: its colour is multiplied by its alpha here.
#
# Slots: 0 = the U-Net output (16 int8 per texel, half resolution, read as 16 raw bytes), 5 = weights (raw buffer,
# 16 bytes per row, 5 rows for each of the 4 sub-pixel positions), 6 / 7 = scale / bias (raw buffers, one float per
# position and channel, rows of 16 bytes), 1..4 = reconstructed images, 8 = previous frame, 9 = UI with alpha,
# 10 = UI colour, 11 / 12 = the two frames of the motion-free blend (all textures read through the texture object at
# +40 of the slot), 32 = the output (base address +0, size +16 w, +20 h, +24 d, texel size +28, pitch +36).
#
# Constant buffer (5 registers, 18 dwords): r0.xy = origin of slot 10, r0.zw = origin of slot 9, r1.xy = origin of
# slot 8, r1.zw = origin of slots 11 and 12 (each added to the thread's pixel), r2.xy = origin of the output pixel,
# r2.zw = extent of the picture (for the debug frame), r3.xy = number of pixels to do (a thread at or past it does
# nothing), r3.z = UI mode (2..5, anything else = no UI), r3.w = debug frame on/off, r4.x = frame counter.
#
# What it computes, per pixel (x, y) (every float operation below in the order and rounding written, ftz):
#   w_k      = sigmoid(fma(scale_k, float(dot_k), bias_k)), k = 0..4. dot_k = the 16 int8 channels of the half-
#              resolution texel (x/2, y/2) (zero outside slot 0) dotted with row (sub + 4k) of the weights, where
#              sub = (x & 1) | ((y << 1) & 2); a row, scale or bias that does not fit its buffer reads as 0.
#              sigmoid(v) = 1 / (1 + ex2(-1.4427 v)) with the fast ex2 and the fast reciprocal.
#   SDR:  A = fma(t1 - t2, w2, t2)                       (rgb of images 1, 2)
#         N = (t1.a, t2.a, t3.a)                          (the fourth image)
#         C = fma(fma(t3.rgb - N, w0, N - A), w1, A)
#   HDR:  A = fma(t3 - t4, w0, t4); B = fma(t1 - t2, w2, t2); C = fma(A - B, w1, B)
#   both: F = fma(s11 - s12, w3, s12); colour = fma(C - F, w4, F)
#   UI modes (r3.z): 2 smoothstep(10 * alpha of slot 9) mix towards slot 10; 3 UI over the colour (slot 9);
#   4 a mask from the distance between slots 8 and 10 mixes the colour with slot 10 (fma(k, colour - s8, s10));
#   5 modes 3 and 4 combined. The debug frame (r3.w != 0) paints a magenta border and a marker bar.
#   Output: each channel saturated, scaled by 4096 (HDR 16384), floored, converted to unorm exactly as the D3D
#   store does it (v * 255 + 2047) >> 12 (HDR (v * 1023 + 8191) >> 14), alpha 1.
