# Emits our own kernel for a stride-2 3x3 layer of the flow networks in the pack's kernel interface
# (p_desc, 48-byte slots p_s0..p_s3, p_s32, the constant buffer by value in p_cb0), so it replaces the translated
# module in a pack as it is: same slots, same grid (8 x 8 threads, one output pixel each, one group z of NCO output
# channels), same bytes.
#
#   shape  in channels  out channels   texel in / out   passes of 16 input channels
#   a112   112 (14 x 8)  224 (z: 8)      8 bytes          7 (two slices each)
#   b32    32 (2 x 16)   64 (z: 16)      16 bytes         2 (one slice each)
#
# The layer, as the modules compute it (cb0 = the root constants, c<n> = dword n):
#   output pixel (gx, gy), group z; input pixel of tap (ex, ey), ex, ey in 0..2:
#       x = 2 gx - 1 + ex - c6          y = 2 gy + ey - c7
#   the tap reads zero when x < 0, x >= c2, y == 0 or y >= c3 + 1 (unsigned: its row 0 and rows past the height are
#   padding; a negative y is past the height), when it falls outside the texture, or when its slice does
#   acc[co]   = s2[NCO z + co] + sum over taps, input channels of in * W       (int8 x int8, dp4a)
#   s         = clamp(acc, -2^(bits-1), 2^(bits-1) - 1)            bits baked into each module
#   out[co]   = clamp(((max(s,0) * c9 + (1 << (sp-1))) >> sp) + ((min(s,0) * s3[NCO z + co] + (1 << (sn-1))) >> sn),
#               -128, 127)         sp = c10 & 31, sn = (c10 >> 8) & 31
#   written to texel (gx, gy + 1) of slice z for gx < c4, gy < c5 (and inside the texture)
# Weights (slot 1): z's passes are NP pieces of 16 bytes each, NP = 36 NCO/4, one piece = 4 output channels x 4 input
# channels (the 4 words of a dp4a): piece h*36 + 4 tap + w of pass p is at 16 ((z PASSES + p) NP + that) bytes, word c =
# output channel 4h + c, byte = input channel 4w + b of the pass. Slots 1-3 are read in 16-byte pieces, a piece past
# the buffer's size (p_sN+32) as zero, as the modules read them.
#
# Usage: python gen_s2_ptx.py <out.ptx> --shape a112|b32 --bits 17|18
import argparse

SHAPES = {  # NCO, passes, slices a pass, texel bytes, input slices read a pass x bytes
    "a112": (8, 7, 2, 8),
    "b32": (16, 2, 1, 16),
}
ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--shape", required=True, choices=sorted(SHAPES))
ap.add_argument("--bits", type=int, required=True)
a = ap.parse_args()

NCO, PASSES, SLP, TX = SHAPES[a.shape]
NH = NCO // 4                  # halves of four output channels
NP = 36 * NH                   # pieces a pass
WORDS = 4                      # dp4a words a tap and pass (16 input channels)
LDV = TX // 4                  # words of one texel load
CMAX = (1 << (a.bits - 1)) - 1
L = []


def w(s=""):
    L.append(s)


w(f"// GENERATED by gen_s2_ptx.py --shape {a.shape} --bits {a.bits} - our own kernel for a stride-2 family B layer.")
w(".version 7.0")
w(".target sm_75")
w(".address_size 64")
w()
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
for s in ("s0", "s1", "s2", "s3", "s32"):
    w(f"    .param .align 16 .b8 p_{s}[48],")
w("    .param .align 16 .b8 p_cb0[48]")
w(") .reqntid 8, 8, 1")
w("{")
w(f"    .shared .align 16 .b32 ws[{PASSES * NP * 4}];")
w("    .reg .pred %p, %pz, %pa, %pb, %pc;")
w("    .reg .pred " + ", ".join(f"%pv{t}" for t in range(9)) + ";")
w("    .reg .b32 %tl, %gx, %gy, %gz, %i, %j, %t, %u, %v, %sz, %idx;")
w("    .reg .b32 %cW, %cH, %cH1, %cLX, %cLY, %cCX, %cCY, %cMul, %cSh;")
w("    .reg .b32 %w0, %h0, %n0, %b0x, %pi0, %sstr, %s2, %s3, %sl;")
w("    .reg .b32 " + ", ".join(f"%xe{e}" for e in range(3)) + ", " + ", ".join(f"%ye{e}" for e in range(3)) + ";")
w("    .reg .b32 " + ", ".join(f"%tb{t}" for t in range(9)) + ";")
w("    .reg .b32 %V0, %V1, %V2, %V3, %P0, %P1, %P2, %P3;")
w("    .reg .b32 " + ", ".join(f"%a{t}_{k}" for t in range(9) for k in range(WORDS)) + ";")
w("    .reg .b32 " + ", ".join(f"%acc{k}" for k in range(NCO)) + ";")
w("    .reg .b32 %mp, %shp, %shn, %rp, %rn, %s, %e, %f, %g, %o0, %o1, %o2, %o3, %pix, %wsb, %pass;")
w("    .reg .b64 %B0, %B1, %B2, %B3, %BO, %r64, %q64;")
w()
w("    mov.u32 %t, %tid.y;")
w("    mov.u32 %u, %tid.x;")
w("    mad.lo.u32 %tl, %t, 8, %u;")
w("    mov.u32 %gx, %ctaid.x;")
w("    mad.lo.u32 %gx, %gx, 8, %u;")
w("    mov.u32 %gy, %ctaid.y;")
w("    mad.lo.u32 %gy, %gy, 8, %t;")
w("    mov.u32 %gz, %ctaid.z;")
w("    ld.param.u32 %cW, [p_cb0+8];")
w("    ld.param.u32 %cH, [p_cb0+12];")
w("    ld.param.u32 %cLX, [p_cb0+16];")
w("    ld.param.u32 %cLY, [p_cb0+20];")
w("    ld.param.u32 %cCX, [p_cb0+24];")
w("    ld.param.u32 %cCY, [p_cb0+28];")
w("    ld.param.u32 %cMul, [p_cb0+36];")
w("    ld.param.u32 %cSh, [p_cb0+40];")
w("    add.s32 %cH1, %cH, 1;")
w("    ld.param.u64 %B1, [p_s1+0];")
w("    ld.param.u32 %sz, [p_s1+32];")
w(f"    // all passes' weights of this group into shared memory ({PASSES * NP} pieces); a piece past the buffer is zero")
w(f"    mul.lo.u32 %idx, %gz, {PASSES * NP};")
for it in range((PASSES * NP + 63) // 64):
    w(f"    add.u32 %i, %tl, {64 * it};")
    w(f"    setp.lt.u32 %pz, %i, {PASSES * NP};")
    w("    add.u32 %j, %idx, %i;")
    w("    mul.lo.u32 %u, %j, 16;")
    w("    add.u32 %u, %u, 16;")
    w("    setp.le.and.u32 %p, %u, %sz, %pz;")
    for k in range(4):
        w(f"    mov.b32 %V{k}, 0;")
    w("    mul.wide.u32 %r64, %j, 16;")
    w("    add.s64 %r64, %B1, %r64;")
    w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%r64];")
    w("    mov.u32 %wsb, ws;")
    w("    mad.lo.u32 %u, %i, 16, %wsb;")
    w("    @%pz st.shared.v4.b32 [%u], {%V0, %V1, %V2, %V3};")
w("    mov.u32 %wsb, ws;")
w()
w("    // the accumulators start at the bias: pieces NH z .. NH z + NH - 1, each read only inside the buffer")
w("    ld.param.u64 %B2, [p_s2+0];")
w("    ld.param.u32 %s2, [p_s2+32];")
for h in range(NH):
    w(f"    mad.lo.u32 %t, %gz, {NH}, {h};")
    w("    mul.lo.u32 %u, %t, 16;")
    w("    add.u32 %v, %u, 16;")
    w("    setp.le.u32 %p, %v, %s2;")
    for k in range(4):
        w(f"    mov.b32 %acc{4 * h + k}, 0;")
    w("    mul.wide.u32 %r64, %u, 1;")
    w("    add.s64 %r64, %B2, %r64;")
    w(f"    @%p ld.global.nc.v4.b32 {{%acc{4 * h}, %acc{4 * h + 1}, %acc{4 * h + 2}, %acc{4 * h + 3}}}, [%r64];")
w()
w("    // the taps' positions and their crop validity (a tap that is invalid reads zero)")
w("    ld.param.u32 %w0, [p_s0+16];")
w("    ld.param.u32 %h0, [p_s0+20];")
w("    ld.param.u32 %n0, [p_s0+24];")
w("    ld.param.u32 %b0x, [p_s0+28];")
w("    ld.param.u32 %pi0, [p_s0+36];")
w("    ld.param.u64 %B0, [p_s0+0];")
w("    mul.lo.u32 %sstr, %h0, %pi0;")
w("    shl.b32 %t, %gx, 1;")
for e in range(3):
    w(f"    add.s32 %xe{e}, %t, {e - 1};")
    w(f"    sub.s32 %xe{e}, %xe{e}, %cCX;")
w("    shl.b32 %t, %gy, 1;")
for e in range(3):
    w(f"    add.s32 %ye{e}, %t, {e};")
    w(f"    sub.s32 %ye{e}, %ye{e}, %cCY;")
for t in range(9):
    ex, ey = t % 3, t // 3
    w(f"    // tap {t}")
    w(f"    setp.ge.s32 %pa, %xe{ex}, 0;")
    w(f"    setp.lo.and.u32 %pa, %xe{ex}, %cW, %pa;")
    w(f"    setp.ne.and.s32 %pa, %ye{ey}, 0, %pa;")
    w(f"    setp.lo.and.u32 %pa, %ye{ey}, %cH1, %pa;")
    w(f"    setp.lo.and.u32 %pa, %xe{ex}, %w0, %pa;")
    w(f"    setp.lo.and.u32 %pa, %ye{ey}, %h0, %pa;")
    w(f"    mov.pred %pv{t}, %pa;")
    w(f"    mul.lo.u32 %tb{t}, %ye{ey}, %pi0;")
    w(f"    mad.lo.u32 %tb{t}, %xe{ex}, %b0x, %tb{t};")
w()
w("    bar.sync 0;")
w("    mov.u32 %pass, 0;")
w("PASS:")
for t in range(9):
    w(f"    // tap {t}: {WORDS} words of the input channels of this pass")
    for k in range(WORDS):
        w(f"    mov.b32 %a{t}_{k}, 0;")
    for sl in range(SLP):
        # slice SLP*pass + sl
        w(f"    mad.lo.u32 %sl, %pass, {SLP}, {sl};")
        w(f"    setp.lo.and.u32 %pb, %sl, %n0, %pv{t};")
        w(f"    mad.lo.u32 %u, %sl, %sstr, %tb{t};")
        w("    cvt.u64.u32 %r64, %u;")
        w("    add.s64 %r64, %B0, %r64;")
        regs = [f"%a{t}_{LDV * sl + k}" for k in range(LDV)]
        w(f"    @%pb ld.global.nc.v{LDV}.b32 {{{', '.join(regs)}}}, [%r64];")
w(f"    mul.lo.u32 %u, %pass, {NP * 16};")
w("    add.u32 %u, %u, %wsb;")
for t in range(9):
    for wd in range(WORDS):
        for h in range(NH):
            off = (h * 36 + t * 4 + wd) * 16
            w(f"    ld.shared.v4.b32 {{%P0, %P1, %P2, %P3}}, [%u+{off}];")
            for c in range(4):
                w(f"    dp4a.s32.s32 %acc{4 * h + c}, %a{t}_{wd}, %P{c}, %acc{4 * h + c};")
w("    add.u32 %pass, %pass, 1;")
w(f"    setp.lt.u32 %p, %pass, {PASSES};")
w("    @%p bra PASS;")
w()
w(f"    // epilogue: clamp to {a.bits} bits, the two-sided requantisation, clamp to int8")
w("    and.b32 %shp, %cSh, 31;")
w("    shr.u32 %shn, %cSh, 8;")
w("    add.u32 %t, %cSh, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rp, 1, %t;")
w("    add.u32 %t, %shn, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rn, 1, %t;")
w("    and.b32 %shn, %shn, 31;")
w("    ld.param.u64 %B3, [p_s3+0];")
w("    ld.param.u32 %s3, [p_s3+32];")
w("    ld.param.u64 %BO, [p_s32+0];")
w("    ld.param.u32 %w0, [p_s32+16];")
w("    ld.param.u32 %h0, [p_s32+20];")
w("    ld.param.u32 %n0, [p_s32+24];")
w("    ld.param.u32 %b0x, [p_s32+28];")
w("    ld.param.u32 %pi0, [p_s32+36];")
w("    add.u32 %t, %gy, 1;")
w("    setp.lo.u32 %pa, %gx, %cLX;")
w("    setp.lo.and.u32 %pa, %gy, %cLY, %pa;")
w("    setp.lo.and.u32 %pa, %gx, %w0, %pa;")
w("    setp.lo.and.u32 %pa, %t, %h0, %pa;")
w("    setp.lo.and.u32 %pa, %gz, %n0, %pa;")
w("    mad.lo.u32 %pix, %gz, %h0, %t;")
w("    mul.lo.u32 %pix, %pix, %pi0;")
w("    mad.lo.u32 %pix, %gx, %b0x, %pix;")
w("    cvt.u64.u32 %r64, %pix;")
w("    add.s64 %BO, %BO, %r64;")
for h in range(NH):
    w(f"    // output channels {4 * h}..{4 * h + 3}: the negative-side multipliers are s3 piece NH z + {h}")
    w(f"    mad.lo.u32 %t, %gz, {NH}, {h};")
    w("    mul.lo.u32 %u, %t, 16;")
    w("    add.u32 %v, %u, 16;")
    w("    setp.le.u32 %p, %v, %s3;")
    for k in range(4):
        w(f"    mov.b32 %V{k}, 0;")
    w("    cvt.u64.u32 %r64, %u;")
    w("    add.s64 %r64, %B3, %r64;")
    w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%r64];")
    for c in range(4):
        w(f"    max.s32 %s, %acc{4 * h + c}, {-CMAX - 1};")
        w(f"    min.s32 %s, %s, {CMAX};")
        w("    max.s32 %e, %s, 0;")
        w("    mul.lo.s32 %e, %e, %cMul;")
        w("    add.s32 %e, %e, %rp;")
        w("    shr.s32 %e, %e, %shp;")
        w("    min.s32 %f, %s, 0;")
        w(f"    mul.lo.s32 %f, %f, %V{c};")
        w("    add.s32 %f, %f, %rn;")
        w("    shr.s32 %f, %f, %shn;")
        w("    add.s32 %e, %e, %f;")
        w("    max.s32 %e, %e, -128;")
        w("    min.s32 %e, %e, 127;")
        w("    and.b32 %e, %e, 255;")
        if c == 0:
            w(f"    mov.b32 %o{h}, %e;")
        else:
            w(f"    bfi.b32 %o{h}, %e, %o{h}, {8 * c}, 8;")
outs = ", ".join(f"%o{h}" for h in range(NH))
w(f"    @%pa st.global.v{NH}.b32 [%BO], {{{outs}}};")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
