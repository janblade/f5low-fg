# Emits our own kernel for a two-source U-Net decoder layer, CIN = COUT = 16, 32 or 64 (the three decoder layers),
# in the pack's kernel interface (p_desc, 48-byte slots p_s0..p_s4, p_s32, the
# constant buffer by value in p_cb0) so it replaces the translated module in a pack as it is: same slots, and
# each block makes the output tile of the replaced grid (16 x 32, 32 x 8 and 8 x 16).
#
# The layer, as verified against the modules it replaces, with the bounds the translated modules use:
#   fused(x, y) = 0 outside [0, W) x [0, H) (W, H = cb dwords 0, 1), else per channel
#                 clamp(trunc((fy1*(fx1*A + fx0*B) + fy0*(fx1*C + fx0*D)) / 16) + t4[x][y], 0, 127)
#                 cx = (x+1)>>1, cy = (y+1)>>1, A = t0[cx-1][cy-1], B = t0[cx][cy-1], C = t0[cx-1][cy], D = t0[cx][cy],
#                 fx1 = 1 + 2*(x&1), fx0 = 4 - fx1 (fy likewise); t0 and t4 read zero outside their own textures
#   out[co]     = clamp(trunc(fma(scale[co], sum over taps, ci of fused * W, bias[co])), 0, 127)
#   weight word = t1[((ci/16) + (co/16)*CS)*576 + (3*(ey+1) + (ex+1))*64 + ((ci/4)%4)*16 + co%16] for the input
#                 at (x+ex, y+ey), bytes = ci%4; CS = CIN/16
# Activations (t0 slot 0, t4 slot 4, the output slot 32) are textures of CS slices of 16 int8 channels:
# (slice * h + y) * pitch + 16x. Scale (slot 2) and bias (slot 3) are COUT floats each.
#
# The fused tile (with its 1-pixel halo) lives in shared memory; the 3x3 conv runs on the tensor cores,
# mma.m16n8k32 (int8: integer sums in any order, so exact). M = 16 pixels of the tile (row-major), N = 8
# output channels, K = 32: two taps of 16 channels (CIN 16; the 10th tap's weights zero) or one tap's
# slice pair. Fragments (grp = lane/4, tg = lane%4): a0/a1 = pixel grp / grp+8, K 4tg..4tg+3 - one word of
# the fused pixel; a2/a3 K 16+4tg..; b0/b1 = output channel grp of the block, the same K - one weight word;
# d0,d1 = pixel grp, output channels 2tg, 2tg+1; d2,d3 = pixel grp+8. CIN 16 keeps its 20 weight words in
# registers, the others read them from shared memory.
# --sm 75 (an RTX 20): each mma.m16n8k32 as four mma.m8n8k16 on the same registers (mma_emit.py).
#
# Usage: python gen_decoder_ptx.py <out.ptx> --cin 16|32|64 [--sm 80|75]
import argparse

from mma_emit import mma_s8

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--cin", type=int, required=True, choices=(16, 32, 64))
ap.add_argument("--sm", type=int, default=80, choices=(75, 80))
a = ap.parse_args()

C = a.cin
CS = C // 16                    # 16-channel slices
TW, TH, NT = {16: (16, 32, 256), 32: (32, 8, 128), 64: (8, 16, 128)}[C]
FW, FH = TW + 2, TH + 2         # fused tile with its halo
NF = FW * FH
NW = NT // 32                   # warps
NP = TW * TH // 16              # m-tiles of 16 pixels
assert NP % NW == 0
MW = NP // NW                   # m-tiles a warp
NB = C // 8                     # n-blocks of 8 output channels
WREG = CS == 1                  # weights in registers
WBYTES = 9 * C * C
L = []


def w(s=""):
    L.append(s)


def kstep_parts():
    """Per K step: (tap, K 0..15 as (slice, channel group in slice)), (tap, K 16..31 ...), tap None = zero."""
    out = []
    if CS == 1:
        for st in range(5):
            out.append(((2 * st, 0), (2 * st + 1 if 2 * st + 1 < 9 else None, 0)))
    else:
        for tap in range(9):
            for j in range(CS // 2):
                out.append(((tap, 2 * j), (tap, 2 * j + 1)))
    return out


def wword(tap, sl, co):
    """Weight word for tap, slice sl, output channel co; the lane adds 16tg + grp (its channel group, output channel)."""
    return (sl + (co // 16) * CS) * 576 + tap * 64 + co % 16


KS = kstep_parts()

# the header names --sm only for an older GPU (the sm 80 packs of 2026-10 were written without it)
SMARG = f" --sm {a.sm}" if a.sm != 80 else ""
w(f"// GENERATED by gen_decoder_ptx.py --cin {C}{SMARG} - our own kernel for the {C} -> {C} two-source U-Net decoder.")
w(".version 7.0")
w(f".target sm_{a.sm}")
w(".address_size 64")
w()
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
for s in ("s0", "s1", "s2", "s3", "s4", "s32", "cb0"):
    w(f"    .param .align 16 .b8 p_{s}[48]" + ("," if s != "cb0" else ""))
w(f") .reqntid {NT}, 1, 1")
w("{")
w(f"    .shared .align 16 .b8 fz[{NF * C}];")
if not WREG:
    w(f"    .shared .align 16 .b8 wt[{WBYTES}];")
w("    .reg .pred %p, %pa, %pb, %pc, %pd, %pt, %pq;")
w("    .reg .b32 %tl, %ox0, %oy0, %W, %H, %i, %lx, %ly, %fx, %fy, %cx, %cy, %ax, %ay, %t, %u, %sl;")
w("    .reg .b32 %w0, %h0, %n0, %pi0, %w4, %h4, %n4, %pi4, %wo, %ho, %pio;")
w("    .reg .b32 %fx1, %fx0, %fy1, %fy0, %a, %b, %c, %d, %e, %n1, %n2;")
w("    .reg .b32 %A<4>, %B<4>, %C<4>, %D<4>, %T<4>, %V<4>;")
w("    .reg .b32 %wid, %lane, %grp, %tg, %a0, %a1, %a2, %a3, %b0, %b1, %sf, %sw, %q0, %q1, %y0, %y1, %x0, %x1;")
if WREG:
    w("    .reg .b32 " + ", ".join(f"%wb{k}_{nb}_{h}" for k in range(len(KS)) for nb in range(NB) for h in range(2)) + ";")
w("    .reg .b32 " + ", ".join(f"%c{nb}_{j}" for nb in range(NB) for j in range(4)) + ";")
w("    .reg .b16 %hv;")
w("    .reg .f32 %f, %s0, %s1, %g0, %g1;")
w("    .reg .b64 %P0, %P4, %PO, %PS, %PB, %PC, %r64;")
w()
w("    mov.u32 %tl, %tid.x;")
w("    mov.u32 %t, %ctaid.x;")
w(f"    mul.lo.u32 %ox0, %t, {TW};")
w("    mov.u32 %t, %ctaid.y;")
w(f"    mul.lo.u32 %oy0, %t, {TH};")
w("    ld.param.v4.b32 {%W, %H, %t, %u}, [p_cb0+0];")
for r, s in (("0", "s0"), ("4", "s4")):
    w(f"    ld.param.u64 %P{r}, [p_{s}+0];")
    w(f"    ld.param.u32 %w{r}, [p_{s}+16];")
    w(f"    ld.param.u32 %h{r}, [p_{s}+20];")
    w(f"    ld.param.u32 %n{r}, [p_{s}+24];")
    w(f"    ld.param.u32 %pi{r}, [p_{s}+36];")
w("    mov.u32 %sf, fz;")
if not WREG:
    w("    mov.u32 %sw, wt;")
    w(f"    // the weights to shared memory: {WBYTES // 16} x 16 bytes")
    w("    ld.param.u64 %PB, [p_s1+0];")
    for it in range((WBYTES // 16 + NT - 1) // NT):
        w(f"    add.u32 %i, %tl, {NT * it};")
        w(f"    setp.lt.u32 %p, %i, {WBYTES // 16};")
        w("    mul.wide.u32 %r64, %i, 16;")
        w("    add.s64 %PS, %PB, %r64;")
        w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%PS];")
        w("    mad.lo.u32 %t, %i, 16, %sw;")
        w("    @%p st.shared.v4.b32 [%t], {%V0, %V1, %V2, %V3};")
w()


def load16(dst, r, xr, yr, pred):
    """dst<4> = slice %sl of the texel at (xr, yr) of texture slot r (P, w, h, n, pi), zero outside it."""
    w(f"    setp.lt.u32 %{pred}, %{xr}, %w{r};")
    w(f"    setp.lt.and.u32 %{pred}, %{yr}, %h{r}, %{pred};")
    w(f"    setp.lt.and.u32 %{pred}, %sl, %n{r}, %{pred};")
    for j in range(4):
        w(f"    mov.b32 %{dst}{j}, 0;")
    w(f"    mad.lo.u32 %t, %sl, %h{r}, %{yr};")
    w(f"    mul.wide.u32 %r64, %t, %pi{r};")
    w(f"    add.s64 %PS, %P{r}, %r64;")
    w(f"    mul.wide.u32 %r64, %{xr}, 16;")
    w(f"    add.s64 %PS, %PS, %r64;")
    w(f"    @%{pred} ld.global.nc.v4.b32 {{%{dst}0, %{dst}1, %{dst}2, %{dst}3}}, [%PS];")


w(f"    // phase 1: the fused tile, fused pixel i at (ox0 - 1 + i % {FW}, oy0 - 1 + i / {FW}), {C} bytes each")
for it in range((NF + NT - 1) // NT):
    w(f"    add.u32 %i, %tl, {NT * it};")
    w(f"    setp.lt.u32 %p, %i, {NF};")
    w(f"    @!%p bra F{it}_END;")
    w(f"    div.u32 %ly, %i, {FW};")
    w(f"    mul.lo.u32 %t, %ly, {FW};")
    w("    sub.u32 %lx, %i, %t;")
    w("    add.s32 %fx, %ox0, %lx;")
    w("    add.s32 %fx, %fx, -1;")
    w("    add.s32 %fy, %oy0, %ly;")
    w("    add.s32 %fy, %fy, -1;")
    w("    setp.lt.u32 %pq, %fx, %W;")
    w("    setp.lt.and.u32 %pq, %fy, %H, %pq;")
    w("    add.u32 %cx, %fx, 1;")
    w("    shr.u32 %cx, %cx, 1;")
    w("    add.u32 %cy, %fy, 1;")
    w("    shr.u32 %cy, %cy, 1;")
    w("    add.s32 %ax, %cx, -1;")
    w("    add.s32 %ay, %cy, -1;")
    w("    and.b32 %t, %fx, 1;")
    w("    shl.b32 %fx1, %t, 1;")
    w("    add.s32 %fx1, %fx1, 1;")
    w("    sub.s32 %fx0, 4, %fx1;")
    w("    and.b32 %t, %fy, 1;")
    w("    shl.b32 %fy1, %t, 1;")
    w("    add.s32 %fy1, %fy1, 1;")
    w("    sub.s32 %fy0, 4, %fy1;")
    for sl in range(CS):
        w(f"    mov.u32 %sl, {sl};")
        for j in range(4):
            w(f"    mov.b32 %V{j}, 0;")
        w(f"    @!%pq bra F{it}_S{sl};")
        load16("A", "0", "ax", "ay", "pa")
        load16("B", "0", "cx", "ay", "pb")
        load16("C", "0", "ax", "cy", "pc")
        load16("D", "0", "cx", "cy", "pd")
        load16("T", "4", "fx", "fy", "pt")
        for ch in range(16):
            wd, by = ch // 4, 8 * (ch % 4)
            w(f"    bfe.s32 %a, %A{wd}, {by}, 8;")
            w(f"    bfe.s32 %b, %B{wd}, {by}, 8;")
            w(f"    bfe.s32 %c, %C{wd}, {by}, 8;")
            w(f"    bfe.s32 %d, %D{wd}, {by}, 8;")
            w(f"    bfe.s32 %e, %T{wd}, {by}, 8;")
            w("    mul.lo.s32 %n1, %fx1, %a;")
            w("    mad.lo.s32 %n1, %fx0, %b, %n1;")
            w("    mul.lo.s32 %n1, %fy1, %n1;")
            w("    mul.lo.s32 %n2, %fx1, %c;")
            w("    mad.lo.s32 %n2, %fx0, %d, %n2;")
            w("    mad.lo.s32 %n1, %fy0, %n2, %n1;")
            w("    div.s32 %n1, %n1, 16;")
            w("    add.s32 %n1, %n1, %e;")
            w("    max.s32 %n1, %n1, 0;")
            w("    min.s32 %n1, %n1, 127;")
            w(f"    bfi.b32 %V{wd}, %n1, %V{wd}, {by}, 8;")
        w(f"F{it}_S{sl}:")
        w(f"    mad.lo.u32 %t, %i, {C}, %sf;")
        w(f"    st.shared.v4.b32 [%t+{16 * sl}], {{%V0, %V1, %V2, %V3}};")
    w(f"F{it}_END:")
w("    bar.sync 0;")
w()
w(f"    // phase 2: the conv, warp wid making m-tiles {MW}wid .. {MW}wid+{MW - 1} (pixels 16k .. 16k+15 of the tile)")
w("    shr.u32 %wid, %tl, 5;")
w("    and.b32 %lane, %tl, 31;")
w("    shr.u32 %grp, %lane, 2;")
w("    and.b32 %tg, %lane, 3;")
if WREG:
    w("    ld.param.u64 %PB, [p_s1+0];")
    w("    mad.lo.u32 %t, %tg, 16, %grp;")
    w("    mul.wide.u32 %r64, %t, 4;")
    w("    add.s64 %PB, %PB, %r64;")
    for k, parts in enumerate(KS):
        for nb in range(NB):
            for h, (tap, sl) in enumerate(parts):
                if tap is None:
                    w(f"    mov.b32 %wb{k}_{nb}_{h}, 0;")
                else:
                    w(f"    ld.global.nc.b32 %wb{k}_{nb}_{h}, [%PB+{4 * wword(tap, sl, 8 * nb)}];")
else:
    w("    mad.lo.u32 %t, %tg, 16, %grp;")
    w("    mad.lo.u32 %sw, %t, 4, %sw;")
w("    ld.param.u64 %PO, [p_s32+0];")
w("    ld.param.u32 %wo, [p_s32+16];")
w("    ld.param.u32 %ho, [p_s32+20];")
w("    ld.param.u32 %pio, [p_s32+36];")
w("    ld.param.u64 %PB, [p_s2+0];")
w("    ld.param.u64 %PC, [p_s3+0];")
w("    shl.b32 %t, %tg, 3;")
w("    cvt.u64.u32 %r64, %t;")
w("    add.s64 %PB, %PB, %r64;")
w("    add.s64 %PC, %PC, %r64;")
for m in range(MW):
    w(f"    // m-tile {MW}wid+{m}: pixels p0 = 16k + grp, p1 = p0 + 8 at (p % {TW}, p / {TW}) of the tile")
    w(f"    mad.lo.u32 %t, %wid, {16 * MW}, {16 * m};")
    w("    add.u32 %t, %t, %grp;")
    for px, (xr, yr, qr) in enumerate((("x0", "y0", "q0"), ("x1", "y1", "q1"))):
        if px:
            w("    add.u32 %t, %t, 8;")
        w(f"    rem.u32 %{xr}, %t, {TW};")
        w(f"    div.u32 %{yr}, %t, {TW};")
        w(f"    mad.lo.u32 %{qr}, %{yr}, {FW}, %{xr};")
        w(f"    mad.lo.u32 %{qr}, %{qr}, {C}, %sf;")
        w(f"    mad.lo.u32 %{qr}, %tg, 4, %{qr};")
    for nb in range(NB):
        for j in range(4):
            w(f"    mov.b32 %c{nb}_{j}, 0;")
    for k, parts in enumerate(KS):
        for h, (tap, sl) in enumerate(parts):
            if tap is None:
                w(f"    mov.b32 %a{2*h}, 0;")
                w(f"    mov.b32 %a{2*h+1}, 0;")
                continue
            ey, ex = tap // 3, tap % 3      # weight tap 3*(ey'+1)+(ex'+1) reads fused tile (x + ex, y + ey)
            off = (ey * FW + ex) * C + 16 * sl
            w(f"    ld.shared.b32 %a{2*h}, [%q0+{off}];")
            w(f"    ld.shared.b32 %a{2*h+1}, [%q1+{off}];")
        for nb in range(NB):
            c = ", ".join(f"%c{nb}_{j}" for j in range(4))
            if WREG:
                bb = f"%wb{k}_{nb}_0, %wb{k}_{nb}_1"
            else:
                for h, (tap, sl) in enumerate(parts):
                    w(f"    ld.shared.b32 %b{h}, [%sw+{4 * wword(tap, sl, 8 * nb)}];")
                bb = "%b0, %b1"
            mma_s8(w, a.sm, c.split(", "), ["%a0", "%a1", "%a2", "%a3"], bb.split(", "),
                   zero={h for h, (tap, _) in enumerate(parts) if tap is None})
    w("    // epilogue: clamp(trunc(fma(scale, acc, bias)), 0, 127); two channels a store, inside the output texture")
    for px, (xr, yr, pr) in enumerate((("x0", "y0", "pa"), ("x1", "y1", "pb"))):
        w(f"    add.u32 %{xr}, %{xr}, %ox0;")
        w(f"    add.u32 %{yr}, %{yr}, %oy0;")
        w(f"    setp.lt.u32 %{pr}, %{xr}, %wo;")
        w(f"    setp.lt.and.u32 %{pr}, %{yr}, %ho, %{pr};")
    for nb in range(NB):
        w(f"    ld.global.nc.v2.f32 {{%s0, %s1}}, [%PB+{32 * nb}];")
        w(f"    ld.global.nc.v2.f32 {{%g0, %g1}}, [%PC+{32 * nb}];")
        sl, boff = nb // 2, 8 * (nb % 2)
        for px, (xr, yr, pr) in enumerate((("x0", "y0", "pa"), ("x1", "y1", "pb"))):
            for j in range(2):
                w(f"    cvt.rn.f32.s32 %f, %c{nb}_{2 * px + j};")
                w(f"    fma.rn.ftz.f32 %f, %s{j}, %f, %g{j};")
                w("    cvt.rzi.ftz.s32.f32 %n1, %f;")
                w("    max.s32 %n1, %n1, 0;")
                w(f"    min.s32 %{'e' if j == 0 else 'n1'}, %n1, 127;")
            w("    bfi.b32 %n1, %n1, %e, 8, 8;")
            w("    cvt.u16.u32 %hv, %n1;")
            w(f"    mad.lo.u32 %t, %ho, {sl}, %{yr};")
            w("    mul.wide.u32 %r64, %t, %pio;")
            w("    add.s64 %PS, %PO, %r64;")
            w(f"    mul.wide.u32 %r64, %{xr}, 16;")
            w("    add.s64 %PS, %PS, %r64;")
            w("    shl.b32 %t, %tg, 1;")
            w("    cvt.u64.u32 %r64, %t;")
            w("    add.s64 %PS, %PS, %r64;")
            w(f"    @%{pr} st.global.u16 [%PS+{boff}], %hv;")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
