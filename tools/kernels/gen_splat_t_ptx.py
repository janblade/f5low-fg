# Emits our own "per generated frame forward splat" kernel (run once per generated frame, after the depth downscale
# and the flow net): every flow vector, scaled by the frame's time t, is pushed to the (up to) four pixels around its
# target as a packed key; the kernels that follow read the winning key per pixel. Same kernel interface as the pack
# expects (p_desc, 48-byte slots p_s0, p_s1, p_s32, the constant buffer by value in p_cb0), grid 8 x 8, one thread
# per source pixel, so it replaces the translated module in a pack as it is.
#
# Slots: 0 = the downscaled depth (a one-channel float texture, fetched by integer texel through the +40 handle),
# 1 = the flow (a raw buffer, 8 bytes per pixel, the first dword = two half floats x and y, the second unused),
# 32 = the key buffer (raw, written with atomic max; zeroed by the caller before every generated frame): W x H dwords
# of x keys followed by W x H dwords of y keys.
#
# Constant buffer (6 dwords used): c0 = (W, H) the area (a thread at or past it only takes part in the barriers),
# c2/c3 = the per-axis scale (float; t / 4 in the game), c4 = the flow buffer's row pitch in pixels, c5 = the flow
# gain (float; 4 in the game).
#
# Per source pixel (x, y), every float operation in the order and rounding written here:
#   m   = gain * (half x, half y of the flow dword)          (flow beyond the buffer's end reads as 0 0)
#   a thread whose m is not finite (either axis) does nothing
#   s   = scale * m                                          (per axis)
#   o   = floor(s + 0.5)                                     (per axis, saturating to int32)
#   z   = 1 - depth(x, y)       (default)    or    depth(x, y)   (with --invert-depth)
#   k16 = min(trunc(32767 * (1 - z)), 32767)                 (the product-sum is one fused multiply-add; negative or
#                                                              NaN gives 0)
#   key = 0x80000000 | (k16 << 16) | bits(s)                 bits() = the 16 bit packing below, per axis
#   for dy, dx in {0, 1}: target = (x + ox + dx, y + oy + dy); if it lies inside W x H, atomic max of key_x into the
#   x plane and key_y into the y plane at that target.
#
# bits(v), the half-float packing this model uses (not IEEE round-to-nearest-even): t = (bits of v) + 0x1000, then
#   sign   = (t >> 16) & 0x8000
#   e      = (t >> 23) & 0xFF,  m = t & 0x7FFFFF
#   e > 112:            ((e - 112) mod 32) << 10  |  m >> 13        (the exponent may carry into the sign bit)
#   102 <= e <= 112:   (((m + 0x7FE000) >> ((125 - e) mod 32)) + 1) >> 1     (a subnormal)
#   e > 143:            additionally 0x7FFF is or-ed in (everything below the sign is set)
#   otherwise 0.  The pieces are or-ed together.  v is finite but the scaled s can still overflow to infinity here.
# The key is therefore ordered by depth first, then by the packing of the motion; the max over all splats into one
# pixel does not depend on the order the threads arrive in.
#
# The work is shared in a 16 x 16 tile of keys in groupshared memory (the group's 8 x 8 block plus 4 on each side) for
# the targets that fall into it, one array per plane; the others go straight to the key buffer. After a barrier the
# tile's non-empty entries (the top bit marks a written key) are maxed into the key buffer too. A write whose address
# does not fit into the slot's byte count (+32) is skipped.
#
# Usage: python gen_splat_t_ptx.py [--invert-depth] <out.ptx>
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("--invert-depth", action="store_true", help="z = depth instead of 1 - depth")
ap.add_argument("out")
a = ap.parse_args()

L = []


def w(s=""):
    L.append(s)


w("// GENERATED by tools/kernels/gen_splat_t_ptx.py - do not edit by hand.")
w("// numthreads 8 x 8 x 1; ftz")
w(".version 7.0")
w(".target sm_75")
w(".address_size 64")
w("")
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
w("    .param .align 16 .b8 p_s0[48],")
w("    .param .align 16 .b8 p_s1[48],")
w("    .param .align 16 .b8 p_s32[48],")
w("    .param .align 16 .b8 p_cb0[32]")
w(") .reqntid 8, 8, 1")
w("{")
w("    .shared .align 16 .b32 tileX[256];")
w("    .shared .align 16 .b32 tileY[256];")
w("    .reg .pred %pin, %pok, %pf, %pv, %pt, %pg, %pw, %pe, %pn, %pd, %po, %pa, %pb;")
w("    .reg .b32 %lin, %tx, %ty, %cx, %cy, %t0, %t1, %t2, %z0, %sa, %sb, %addr0, %addr1;")
w("    .reg .b32 %W, %H, %scx, %scy, %pitch, %gain, %sizeS, %sizeF, %fsz;")
w("    .reg .b32 %off, %end, %fw, %f0, %f1, %m0, %m1, %s0, %s1, %d0, %d1, %d2, %d3, %zz, %nz, %kk, %k16;")
w("    .reg .b32 %hx, %hy, %keyx, %keyy, %ox, %oy, %px, %py, %bx0, %by0;")
w("    .reg .b32 %h_b, %h_s, %h_e, %h_m, %h_sg, %h_n, %h_d, %h_o, %h_t;")
w("    .reg .b32 %qx, %qy, %rx, %ry, %o0, %o1, %i, %j, %v0, %v1, %fx, %fy;")
w("    .reg .b16 %hh0, %hh1;")
w("    .reg .b64 %q0, %q1, %sbase, %fbase, %a64;")
w("")
w("    mov.u32 %t0, %tid.x;")
w("    mov.u32 %t1, %tid.y;")
w("    shl.b32 %lin, %t1, 3;")
w("    add.s32 %lin, %lin, %t0;")
w("    mov.u32 %t2, %ctaid.x;")
w("    mad.lo.s32 %tx, %t2, 8, %t0;")
w("    mov.u32 %t2, %ctaid.y;")
w("    mad.lo.s32 %ty, %t2, 8, %t1;")
w("    // empty the two tiles: 64 threads, four consecutive entries of each array apiece")
w("    mov.b32 %z0, 0;")
w("    shl.b32 %t2, %lin, 4;")
w("    mov.u32 %addr0, tileX;")
w("    add.s32 %addr0, %addr0, %t2;")
w("    st.shared.v4.b32 [%addr0], {%z0, %z0, %z0, %z0};")
w("    mov.u32 %addr1, tileY;")
w("    add.s32 %addr1, %addr1, %t2;")
w("    st.shared.v4.b32 [%addr1], {%z0, %z0, %z0, %z0};")
w("    bar.sync 0;")
w("    ld.param.v4.b32 {%W, %H, %scx, %scy}, [p_cb0+0];")
w("    ld.param.v2.b32 {%pitch, %gain}, [p_cb0+16];")
w("    ld.param.u64 %sbase, [p_s32+0];")
w("    ld.param.u32 %sizeS, [p_s32+32];")
w("    // the tile's origin in image coordinates")
w("    mov.u32 %t2, %ctaid.x;")
w("    shl.b32 %bx0, %t2, 3;")
w("    add.s32 %bx0, %bx0, -4;")
w("    mov.u32 %t2, %ctaid.y;")
w("    shl.b32 %by0, %t2, 3;")
w("    add.s32 %by0, %by0, -4;")
w("    setp.lo.u32 %pin, %tx, %W;")
w("    setp.lo.and.u32 %pin, %ty, %H, %pin;")
w("    @!%pin bra FLUSH;")
w("    // the flow: first dword of the pixel's 8 bytes, zero past the end of the buffer")
w("    mad.lo.s32 %off, %ty, %pitch, %tx;")
w("    shl.b32 %off, %off, 3;")
w("    ld.param.u64 %fbase, [p_s1+0];")
w("    ld.param.u32 %fsz, [p_s1+32];")
w("    add.s32 %end, %off, 8;")
w("    setp.le.u32 %pok, %end, %fsz;")
w("    cvt.u64.u32 %a64, %off;")
w("    add.s64 %a64, %fbase, %a64;")
w("    mov.b32 %fw, 0;")
w("    @%pok ld.global.nc.b32 %fw, [%a64];")
w("    mov.b32 {%hh0, %hh1}, %fw;")
w("    cvt.f32.f16 %f0, %hh0;")
w("    cvt.f32.f16 %f1, %hh1;")
w("    mul.rn.ftz.f32 %m0, %gain, %f0;")
w("    mul.rn.ftz.f32 %m1, %gain, %f1;")
w("    ld.param.u64 %q0, [p_s0+40];")
w("    tex.2d.v4.f32.s32 {%d0, %d1, %d2, %d3}, [%q0, {%tx, %ty}];")
w("    testp.finite.f32 %pa, %m0;")
w("    testp.finite.f32 %pb, %m1;")
w("    and.pred %pv, %pa, %pb;")
w("    @!%pv bra FLUSH;")
w("    mul.rn.ftz.f32 %s0, %scx, %m0;")
w("    mul.rn.ftz.f32 %s1, %scy, %m1;")
w("    // the pixel the motion lands on")
w("    add.rn.ftz.f32 %fx, %s0, 0f3F000000;")
w("    add.rn.ftz.f32 %fy, %s1, 0f3F000000;")
w("    cvt.rmi.ftz.f32.f32 %fx, %fx;")
w("    cvt.rmi.ftz.f32.f32 %fy, %fy;")
w("    cvt.rzi.ftz.s32.f32 %ox, %fx;")
w("    cvt.rzi.ftz.s32.f32 %oy, %fy;")
w("    add.s32 %px, %ox, %tx;")
w("    add.s32 %py, %oy, %ty;")
w("    // the depth part of the key")
if a.invert_depth:
    w("    mov.b32 %zz, %d0;")
else:
    w("    sub.rn.ftz.f32 %zz, 0f3F800000, %d0;")
w("    neg.ftz.f32 %nz, %zz;")
w("    fma.rn.ftz.f32 %kk, %nz, 0f46FFFE00, 0f46FFFE00;")
w("    cvt.rzi.ftz.u32.f32 %k16, %kk;")
w("    min.u32 %k16, %k16, 32767;")
w("    shl.b32 %k16, %k16, 16;")
w("    or.b32 %k16, %k16, -2147483648;")


def half_bits(src, dst):
    """dst = the model's 16-bit packing of the float in src (see the header)."""
    w(f"    add.s32 %h_b, {src}, 4096;")
    w("    shr.u32 %h_s, %h_b, 23;")
    w("    and.b32 %h_e, %h_s, 255;")
    w("    and.b32 %h_m, %h_b, 8388607;")
    w("    shr.u32 %h_sg, %h_b, 16;")
    w("    and.b32 %h_sg, %h_sg, 32768;")
    w("    setp.hi.u32 %pn, %h_e, 112;")
    w("    add.s32 %h_n, %h_s, 16;")
    w("    shl.b32 %h_n, %h_n, 10;")
    w("    and.b32 %h_n, %h_n, 31744;")
    w("    shr.u32 %h_t, %h_m, 13;")
    w("    or.b32 %h_n, %h_n, %h_t;")
    w("    selp.b32 %h_n, %h_n, 0, %pn;")
    w("    add.s32 %h_t, %h_e, -102;")
    w("    setp.lo.u32 %pd, %h_t, 11;")
    w("    add.s32 %h_d, %h_m, 8384512;")
    w("    sub.s32 %h_t, 125, %h_s;")
    w("    and.b32 %h_t, %h_t, 31;")
    w("    shr.u32 %h_d, %h_d, %h_t;")
    w("    add.s32 %h_d, %h_d, 1;")
    w("    shr.u32 %h_d, %h_d, 1;")
    w("    selp.b32 %h_d, %h_d, 0, %pd;")
    w("    setp.hi.u32 %po, %h_e, 143;")
    w("    selp.b32 %h_o, 32767, 0, %po;")
    w("    or.b32 %h_t, %h_sg, %h_o;")
    w("    or.b32 %h_t, %h_t, %h_n;")
    w(f"    or.b32 {dst}, %h_t, %h_d;")


half_bits("%s0", "%hx")
half_bits("%s1", "%hy")
w("    or.b32 %keyx, %hx, %k16;")
w("    or.b32 %keyy, %hy, %k16;")
w("    // the four targets")
w("    ld.param.u32 %fsz, [p_s32+32];")
for n in range(4):
    dx, dy = n & 1, n >> 1
    w(f"    // target {n}: (+{dx}, +{dy})")
    w(f"    add.s32 %qx, %px, {dx};")
    w(f"    add.s32 %qy, %py, {dy};")
    w("    setp.lo.u32 %pt, %qx, %W;")
    w("    setp.lo.and.u32 %pt, %qy, %H, %pt;")
    w("    sub.s32 %rx, %qx, %bx0;")
    w("    sub.s32 %ry, %qy, %by0;")
    w("    or.b32 %t0, %rx, %ry;")
    w("    setp.lo.u32 %pg, %t0, 16;")
    w("    and.pred %pw, %pt, %pg;")           # into the tile
    w("    not.pred %pe, %pg;")
    w("    and.pred %pe, %pe, %pt;")           # straight to the key buffer
    w("    shl.b32 %t0, %ry, 4;")
    w("    add.s32 %t0, %t0, %rx;")
    w("    shl.b32 %t0, %t0, 2;")
    w("    mov.u32 %addr0, tileX;")
    w("    add.s32 %addr0, %addr0, %t0;")
    w("    mov.u32 %addr1, tileY;")
    w("    add.s32 %addr1, %addr1, %t0;")
    w("    @%pw red.shared.max.u32 [%addr0], %keyx;")
    w("    @%pw red.shared.max.u32 [%addr1], %keyy;")
    w("    mad.lo.s32 %o0, %qy, %W, %qx;")
    w("    shl.b32 %o0, %o0, 2;")
    w("    add.s32 %t0, %qy, %H;")
    w("    mad.lo.s32 %o1, %t0, %W, %qx;")
    w("    shl.b32 %o1, %o1, 2;")
    w("    add.s32 %t1, %o0, 4;")
    w("    setp.le.and.u32 %pa, %t1, %sizeS, %pe;")
    w("    add.s32 %t1, %o1, 4;")
    w("    setp.le.and.u32 %pb, %t1, %sizeS, %pe;")
    w("    cvt.u64.u32 %a64, %o0;")
    w("    add.s64 %a64, %sbase, %a64;")
    w("    @%pa red.global.max.u32 [%a64], %keyx;")
    w("    cvt.u64.u32 %a64, %o1;")
    w("    add.s64 %a64, %sbase, %a64;")
    w("    @%pb red.global.max.u32 [%a64], %keyy;")
w("FLUSH:")
w("    bar.sync 0;")
w("    // the tile's keys into the key buffer: this thread takes entries lin, lin + 64, lin + 128, lin + 192")
w("    and.b32 %qx, %lin, 15;")
w("    add.s32 %qx, %qx, %bx0;")
w("    shr.u32 %t0, %lin, 4;")
w("    add.s32 %qy, %t0, %by0;")
w("    setp.lo.u32 %pg, %qx, %W;")
w("    mov.u32 %addr0, tileX;")
w("    shl.b32 %t2, %lin, 2;")
w("    add.s32 %addr0, %addr0, %t2;")
w("    mov.u32 %addr1, tileY;")
w("    add.s32 %addr1, %addr1, %t2;")
w("    ld.param.u64 %sbase, [p_s32+0];")
w("    ld.param.u32 %sizeS, [p_s32+32];")
for k in range(4):
    w(f"    // entries {64 * k} + lin")
    w(f"    ld.shared.b32 %v0, [%addr0+{256 * k}];")
    w(f"    ld.shared.b32 %v1, [%addr1+{256 * k}];")
    w("    setp.lt.s32 %pt, %v0, 0;")
    w("    and.pred %pt, %pt, %pg;")
    w(f"    add.s32 %ry, %qy, {4 * k};")
    w("    setp.lo.and.u32 %pt, %ry, %H, %pt;")
    w("    mad.lo.s32 %o0, %ry, %W, %qx;")
    w("    shl.b32 %o0, %o0, 2;")
    w("    add.s32 %t0, %ry, %H;")
    w("    mad.lo.s32 %o1, %t0, %W, %qx;")
    w("    shl.b32 %o1, %o1, 2;")
    w("    add.s32 %t1, %o0, 4;")
    w("    setp.le.and.u32 %pa, %t1, %sizeS, %pt;")
    w("    add.s32 %t1, %o1, 4;")
    w("    setp.le.and.u32 %pb, %t1, %sizeS, %pt;")
    w("    cvt.u64.u32 %a64, %o0;")
    w("    add.s64 %a64, %sbase, %a64;")
    w("    @%pa red.global.max.u32 [%a64], %v0;")
    w("    cvt.u64.u32 %a64, %o1;")
    w("    add.s64 %a64, %sbase, %a64;")
    w("    @%pb red.global.max.u32 [%a64], %v1;")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
