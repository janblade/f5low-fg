# Emits our own kernel for a stride-1 family B 3x3 layer of the flow networks (FAMILY_B.md) - net A's 224 -> 224
# (17-bit clamp, and its 19 / 20-bit variants) or net B's 64 -> 64 (18 bits, and a 17-bit twin that differs only
# in the clamp; the multi-frame model runs it at 19) - in the
# pack's kernel interface (p_desc, 48-byte slots p_s0..p_s3, p_s32, the constant buffer by value in p_cb0) so it
# replaces the translated module in a pack as it is: same slots, same grid, and each block makes the output tile
# of the replaced group (8 x 8 pixels, one group z of G output channels).
#
#   shape   CIN  G   texel        blocks of 16 input channels
#   a224    224  8   8 bytes      14 x 1152 bytes
#   b64      64  16  16 bytes      4 x 2304 bytes
#
# The layer, as the translated modules compute it:
#   acc[co]  = s2[Gz + co] + sum over taps (ey, ex in 0..2), ci < CIN of in[ci](x - 1 + ex, y + ey) * W
#              input texel (x', y') read as zero when x' < 0, x' >= cb0[2], y' == 0 or y' > cb0[3] (its row 0 and
#              rows past the height are padding), or outside the texture
#   s        = clamp(acc, -2^(bits-1), 2^(bits-1) - 1)          bits baked into each module
#   out[co]  = clamp(((max(s,0)*mulPos + (1 << (sp-1))) >> sp) + ((min(s,0)*s3[Gz + co] + (1 << (sn-1))) >> sn),
#              -128, 127)      mulPos = cb0 dword 9, sp = dword 10 & 31, sn = (dword 10 >> 8) & 31
#   written to texel (x, y + 1) of array slice z, for x < cb0[4], y < cb0[5]
# Activations: texture arrays of texel-size int8 channels, (slice * h + y) * pitch + texel * x. Weights (slot 1):
# group z's blocks at ((CIN/16) z + block) * 144G bytes, byte (co/4)*576 + tap*64 + ((ci%16)/4)*16 + (co%4)*4 +
# ci%4, tap = 3*ey + ex. Slots 1-3 are read in 16-byte pieces, a piece past the buffer's size (p_sN+32) as zero,
# as the modules read them.
#
# On the tensor cores, mma.m16n8k32 (int8: integer sums in any order, so exact): M = 16 pixels of the tile (two
# rows of 8), N = 8 output channels (G/8 n-blocks), K = one tap's 32 input channels. Each of the CIN/32 passes
# stages 32 input channels of the 10 x 10 halo (12-word pixel stride: no bank conflicts) and their two weight
# blocks in shared memory; warp w makes m-tiles 2w and 2w+1. Fragments (grp = lane/4, tg = lane%4): a0/a1 = pixel
# grp / grp+8, channels 4tg..+3; a2/a3 channels 16+4tg..; b0/b1 = output channel 8nb + grp, the same channels;
# d0,d1 = pixel grp, output channels 8nb + 2tg, +1; d2,d3 = pixel grp+8. --sm 75 (an RTX 20): each mma.m16n8k32
# as four mma.m8n8k16 on the same registers (mma_emit.py).
#
# Usage: python gen_famb_ptx.py <out.ptx> --shape a224|b64 --bits 17|18|19|20 [--sm 80|75]
import argparse

from mma_emit import mma_s8

SHAPES = {  # cin, group, texel bytes, clamp widths of the modules
    "a224": (224, 8, 8, (17, 19, 20)),
    "b64": (64, 16, 16, (17, 18, 19)),
}
ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--shape", required=True, choices=sorted(SHAPES))
ap.add_argument("--bits", type=int, required=True)
ap.add_argument("--sm", type=int, default=80, choices=(75, 80))
a = ap.parse_args()

CIN, G, TX, WIDTHS = SHAPES[a.shape]
if a.bits not in WIDTHS:
    ap.error(f"--shape {a.shape} takes --bits {'|'.join(map(str, WIDTHS))}")
NB = G // 8                     # n-blocks of 8 output channels
CB = CIN // 16                  # weight blocks a group
PASSES = CIN // 32
LPP = 32 // TX                  # texel loads a staged pixel
HW = 10                         # halo tile side
PSTRIDE = 12                    # words per staged pixel (8 used)
HALO_WORDS = HW * HW * PSTRIDE
WBLK = 144 * G                  # bytes per 16 input channels
CMAX = (1 << (a.bits - 1)) - 1
V = [f"%V{k}" for k in range(TX // 4)]
L = []


def w(s=""):
    L.append(s)


w(f"// GENERATED by gen_famb_ptx.py --shape {a.shape} --bits {a.bits} --sm {a.sm} - our own kernel for a "
  f"{CIN} -> {CIN} family B layer.")
w(".version 7.0")
w(f".target sm_{a.sm}")
w(".address_size 64")
w()
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
for s in ("s0", "s1", "s2", "s3", "s32"):
    w(f"    .param .align 16 .b8 p_{s}[48],")
w("    .param .align 16 .b8 p_cb0[48]")
w(") .reqntid 8, 8, 1")
w("{")
w(f"    .shared .align 16 .b32 hs[{HALO_WORDS}];")
w(f"    .shared .align 16 .b32 ws[{2 * WBLK // 4}];")
w("    .reg .pred %p, %pz, %pa;")
w("    .reg .b32 %tl, %cx, %cy, %cz, %i, %j, %t, %u, %lx, %ly, %fx, %fy, %q, %sl;")
w("    .reg .b32 %w0, %h0, %n0, %b0x, %pi0, %wo, %ho, %no, %pio, %vw, %vh, %lw, %lh;")
w("    .reg .b32 %wid, %lane, %grp, %tg, %hsb, %wsb, %qa, %qw, %V0, %V1, %V2, %V3;")
w("    .reg .b32 %a0, %a1, %a2, %a3, %mp, %sh, %shp, %shn, %rp, %rn, %s, %e, %f, %g, %bt;")
w("    .reg .b32 " + ", ".join(f"%bw{nb}_{h}" for nb in range(NB) for h in range(2)) + ";")
w("    .reg .b32 " + ", ".join(f"%c{m}_{nb}_{k}" for m in range(2) for nb in range(NB) for k in range(4)) + ";")
w("    .reg .b32 " + ", ".join(f"%t{s}{nb}{h}" for s in (2, 3) for nb in range(NB) for h in "ab") + ";")
w("    .reg .b32 %px, %py, %oy, %zw, %z2, %z3;")
w("    .reg .b16 %hv;")
w("    .reg .b64 %P0, %PW, %PS, %r64, %PO, %P2, %P3;")
w()
w("    mov.u32 %t, %tid.y;")
w("    mov.u32 %u, %tid.x;")
w("    mad.lo.u32 %tl, %t, 8, %u;")
w("    mov.u32 %cx, %ctaid.x;")
w("    mov.u32 %cy, %ctaid.y;")
w("    mov.u32 %cz, %ctaid.z;")
w("    ld.param.u64 %P0, [p_s0+0];")
w("    ld.param.u32 %w0, [p_s0+16];")
w("    ld.param.u32 %h0, [p_s0+20];")
w("    ld.param.u32 %n0, [p_s0+24];")
w("    ld.param.u32 %b0x, [p_s0+28];")
w("    ld.param.u32 %pi0, [p_s0+36];")
w(f"    // built for {TX}-byte texels in and out: any other view writes nothing rather than wrong bytes")
w("    ld.param.u32 %bt, [p_s32+28];")
w(f"    setp.ne.u32 %p, %b0x, {TX};")
w(f"    setp.ne.or.u32 %p, %bt, {TX}, %p;")
w("    @%p ret;")
w("    ld.param.u64 %PW, [p_s1+0];")
w("    ld.param.u32 %zw, [p_s1+32];")
w("    ld.param.u32 %vw, [p_cb0+8];")
w("    ld.param.u32 %vh, [p_cb0+12];")
w("    add.u32 %vh, %vh, 1;")
w("    mov.u32 %hsb, hs;")
w("    mov.u32 %wsb, ws;")
w("    shr.u32 %wid, %tl, 5;")
w("    and.b32 %lane, %tl, 31;")
w("    shr.u32 %grp, %lane, 2;")
w("    and.b32 %tg, %lane, 3;")
w("    // this lane's A words: m-tile 2wid + m, pixel grp -> tile (grp, 2(2wid+m)), + tg; pixel grp+8 one row down")
w(f"    mul.lo.u32 %qa, %wid, {4 * HW};")
w("    add.u32 %qa, %qa, %grp;")
w(f"    mul.lo.u32 %qa, %qa, {PSTRIDE * 4};")
w("    mad.lo.u32 %qa, %tg, 4, %qa;")
w("    add.u32 %qa, %qa, %hsb;")
w("    // this lane's B word: output channel grp (+ 8nb: + 1152 bytes), + tg")
w("    shr.u32 %t, %grp, 2;")
w("    mul.lo.u32 %qw, %t, 576;")
w("    and.b32 %t, %grp, 3;")
w("    mad.lo.u32 %qw, %t, 4, %qw;")
w("    mad.lo.u32 %qw, %tg, 16, %qw;")
w("    add.u32 %qw, %qw, %wsb;")
w(f"    // accumulators start at s2[{G}z + co], co = 8nb + 2tg, +1; each 16-byte piece read only inside the buffer")
w("    ld.param.u64 %P2, [p_s2+0];")
w("    ld.param.u32 %z2, [p_s2+32];")
w("    ld.param.u64 %P3, [p_s3+0];")
w("    ld.param.u32 %z3, [p_s3+32];")
w(f"    shl.b32 %t, %cz, {G.bit_length() - 1};")
w("    mad.lo.u32 %t, %tg, 2, %t;")
w("    mul.wide.u32 %r64, %t, 4;")
w("    add.s64 %P2, %P2, %r64;")
w("    add.s64 %P3, %P3, %r64;")
for nb in range(NB):
    w(f"    // n-block {nb}: dwords + {8 * nb}, in the piece ((Gz + 8nb + 2tg) * 4) & ~15")
    w(f"    add.u32 %u, %t, {8 * nb};")
    w("    shl.b32 %u, %u, 2;")
    w("    and.b32 %u, %u, -16;")
    w("    add.u32 %u, %u, 16;")
    for d, z, r in (("P2", "z2", "2"), ("P3", "z3", "3")):
        w(f"    mov.b32 %t{r}{nb}a, 0;")
        w(f"    mov.b32 %t{r}{nb}b, 0;")
        w(f"    setp.le.u32 %p, %u, %{z};")
        w(f"    @%p ld.global.nc.v2.u32 {{%t{r}{nb}a, %t{r}{nb}b}}, [%{d}+{32 * nb}];")
for m in range(2):
    for nb in range(NB):
        for k, h in enumerate("abab"):
            w(f"    mov.b32 %c{m}_{nb}_{k}, %t2{nb}{h};")
w("    mov.u32 %j, 0;")
w("PASS:")
w("    bar.sync 0;")
w(f"    // the weights of input channels 32j..32j+31: 2 blocks of {WBLK} bytes at ({CB}z + 2j) * {WBLK}")
w(f"    mul.lo.u32 %t, %cz, {CB};")
w("    shl.b32 %u, %j, 1;")
w("    add.u32 %t, %t, %u;")
w(f"    mul.lo.u32 %t, %t, {WBLK};")
w("    cvt.u64.u32 %r64, %t;")
w("    add.s64 %PS, %PW, %r64;")
for it in range((2 * WBLK // 16 + 63) // 64):
    w(f"    add.u32 %i, %tl, {64 * it};")
    w(f"    setp.lt.u32 %pz, %i, {2 * WBLK // 16};")
    w("    // inside the buffer: the pass's offset + 16i + 16 <= size")
    w("    mad.lo.u32 %u, %i, 16, %t;")
    w("    add.u32 %u, %u, 16;")
    w("    setp.le.and.u32 %p, %u, %zw, %pz;")
    for k in range(4):
        w(f"    mov.b32 %V{k}, 0;")
    w("    mul.wide.u32 %r64, %i, 16;")
    w("    add.s64 %r64, %PS, %r64;")
    w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%r64];")
    w("    mad.lo.u32 %u, %i, 16, %wsb;")
    w("    @%pz st.shared.v4.b32 [%u], {%V0, %V1, %V2, %V3};")
w(f"    // the halo: {HW * HW} pixels x {LPP} slices ({LPP}j..) of {TX} channels; pixel (lx, ly) is input "
  "(8cx - 1 + lx, 8cy + ly)")
for it in range((HW * HW * LPP + 63) // 64):
    w(f"    add.u32 %i, %tl, {64 * it};")
    w(f"    setp.lt.u32 %pz, %i, {HW * HW * LPP};")
    w(f"    @!%pz bra H{it}_END;")
    w(f"    rem.u32 %q, %i, {LPP};")
    w(f"    div.u32 %t, %i, {LPP};")
    w(f"    rem.u32 %lx, %t, {HW};")
    w(f"    div.u32 %ly, %t, {HW};")
    w("    shl.b32 %fx, %cx, 3;")
    w("    add.u32 %fx, %fx, %lx;")
    w("    add.s32 %fx, %fx, -1;")
    w("    shl.b32 %fy, %cy, 3;")
    w("    add.u32 %fy, %fy, %ly;")
    w(f"    mad.lo.u32 %sl, %j, {LPP}, %q;")
    w("    setp.lt.u32 %p, %fx, %vw;")
    w("    setp.ne.and.u32 %p, %fy, 0, %p;")
    w("    setp.lt.and.u32 %p, %fy, %vh, %p;")
    w("    setp.lt.and.u32 %p, %fx, %w0, %p;")
    w("    setp.lt.and.u32 %p, %fy, %h0, %p;")
    w("    setp.lt.and.u32 %p, %sl, %n0, %p;")
    for r in V:
        w(f"    mov.b32 {r}, 0;")
    w("    mad.lo.u32 %u, %sl, %h0, %fy;")
    w("    mul.lo.u32 %u, %u, %pi0;")
    w("    mad.lo.u32 %u, %fx, %b0x, %u;")
    w("    cvt.u64.u32 %r64, %u;")
    w("    add.s64 %r64, %P0, %r64;")
    w(f"    @%p ld.global.nc.v{len(V)}.b32 {{{', '.join(V)}}}, [%r64];")
    w(f"    mad.lo.u32 %t, %t, {PSTRIDE * 4}, %hsb;")
    w(f"    mad.lo.u32 %t, %q, {TX}, %t;")
    w(f"    st.shared.v{len(V)}.b32 [%t], {{{', '.join(V)}}};")
    w(f"H{it}_END:")
w("    bar.sync 0;")
for tap in range(9):
    ey, ex = tap // 3, tap % 3
    w(f"    // tap {tap}: halo (x + {ex}, y + {ey})")
    for nb in range(NB):
        w(f"    ld.shared.b32 %bw{nb}_0, [%qw+{1152 * nb + tap * 64}];")
        w(f"    ld.shared.b32 %bw{nb}_1, [%qw+{WBLK + 1152 * nb + tap * 64}];")
    for m in range(2):
        base = ((2 * m + ey) * HW + ex) * PSTRIDE * 4
        w(f"    ld.shared.b32 %a0, [%qa+{base}];")
        w(f"    ld.shared.b32 %a1, [%qa+{base + HW * PSTRIDE * 4}];")
        w(f"    ld.shared.b32 %a2, [%qa+{base + 16}];")
        w(f"    ld.shared.b32 %a3, [%qa+{base + HW * PSTRIDE * 4 + 16}];")
        for nb in range(NB):
            mma_s8(w, a.sm, [f"%c{m}_{nb}_{k}" for k in range(4)], ["%a0", "%a1", "%a2", "%a3"],
                   [f"%bw{nb}_0", f"%bw{nb}_1"])
w("    add.u32 %j, %j, 1;")
w(f"    setp.lt.u32 %p, %j, {PASSES};")
w("    @%p bra PASS;")
w()
w(f"    // epilogue: clamp to {a.bits} bits, the two-sided requantisation, clamp to int8")
w("    ld.param.u32 %mp, [p_cb0+36];")
w("    ld.param.u32 %sh, [p_cb0+40];")
w("    and.b32 %shp, %sh, 31;")
w("    shr.u32 %shn, %sh, 8;")
w("    and.b32 %shn, %shn, 31;")
w("    add.u32 %t, %shp, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rp, 1, %t;")
w("    add.u32 %t, %shn, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rn, 1, %t;")
w("    ld.param.u32 %lw, [p_cb0+16];")
w("    ld.param.u32 %lh, [p_cb0+20];")
w("    ld.param.u64 %PO, [p_s32+0];")
w("    ld.param.u32 %wo, [p_s32+16];")
w("    ld.param.u32 %ho, [p_s32+20];")
w("    ld.param.u32 %no, [p_s32+24];")
w("    ld.param.u32 %pio, [p_s32+36];")


def requant(src, t3, dst):
    w(f"    max.s32 %s, {src}, {-CMAX - 1};")
    w(f"    min.s32 %s, %s, {CMAX};")
    w("    max.s32 %e, %s, 0;")
    w("    mul.lo.s32 %e, %e, %mp;")
    w("    add.s32 %e, %e, %rp;")
    w("    shr.s32 %e, %e, %shp;")
    w("    min.s32 %f, %s, 0;")
    w(f"    mul.lo.s32 %f, %f, {t3};")
    w("    add.s32 %f, %f, %rn;")
    w("    shr.s32 %f, %f, %shn;")
    w("    add.s32 %e, %e, %f;")
    w("    max.s32 %e, %e, -128;")
    w(f"    min.s32 {dst}, %e, 127;")


for m in range(2):
    for half in range(2):
        # pixel grp (+8: one row down) of m-tile 2wid + m: tile (grp, 2(2wid + m) + half)
        w(f"    // m-tile 2wid+{m}, pixel row {half}")
        w("    shl.b32 %px, %cx, 3;")
        w("    add.u32 %px, %px, %grp;")
        w("    shl.b32 %py, %cy, 3;")
        w("    mad.lo.u32 %py, %wid, 4, %py;")
        w(f"    add.u32 %py, %py, {2 * m + half};")
        w("    setp.lt.u32 %pa, %px, %lw;")
        w("    setp.lt.and.u32 %pa, %py, %lh, %pa;")
        w("    add.u32 %oy, %py, 1;")
        w("    setp.lt.and.u32 %pa, %px, %wo, %pa;")
        w("    setp.lt.and.u32 %pa, %oy, %ho, %pa;")
        w("    setp.lt.and.u32 %pa, %cz, %no, %pa;")
        w("    mad.lo.u32 %u, %cz, %ho, %oy;")
        w("    mul.lo.u32 %u, %u, %pio;")
        w("    mad.lo.u32 %u, %px, %bt, %u;")
        w("    mad.lo.u32 %u, %tg, 2, %u;")
        w("    cvt.u64.u32 %r64, %u;")
        w("    add.s64 %r64, %PO, %r64;")
        for nb in range(NB):
            requant(f"%c{m}_{nb}_{2 * half}", f"%t3{nb}a", "%g")
            requant(f"%c{m}_{nb}_{2 * half + 1}", f"%t3{nb}b", "%e")
            w("    and.b32 %g, %g, 255;")
            w("    bfi.b32 %g, %e, %g, 8, 8;")
            w("    cvt.u16.u32 %hv, %g;")
            w(f"    @%pa st.global.u16 [%r64+{8 * nb}], %hv;")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
