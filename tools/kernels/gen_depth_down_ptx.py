# Emits our own "depth downscale" kernel (run once per app frame, before the per-t splat): a box downscale of the
# previous depth texture, in the pack's kernel interface (p_desc, 48-byte slots p_s0 and p_s32, the constant buffer
# by value in p_cb0) so it replaces the translated module in a pack as it is. Grid: 8 x 8 threads per block, one thread
# per output pixel.
#
# Constant buffer (6 dwords used): r0 = source rectangle (x, y, w, h) inside slot 0, r1.xy = output size (ow, oh); a
# thread at or past (ow, oh) does nothing. Slot 0 = the depth (a one-channel float texture, read through the texture
# object at +40 of the slot), slot 32 = the output (4-byte texels), written through the slot's base address (+0) with its
# size (+16 w, +20 h, +24 d), texel size (+28) and row pitch (+36).
#
# What it computes, per output pixel (x, y), with every float operation in the order and rounding written here:
#   lo(p, n, size) = floor(size * ((p + 0.01) / n))          (the division is the fast approximate one)
#   hi(p, n, size) = min(ceil(size * ((p + 0.99) / n)), size)
#   box            = [lo(x, ow, w), hi(x, ow, w)) x [lo(y, oh, h), hi(y, oh, h)) of the source rectangle
#   out            = (sum of the box's depth texels, row by row, left to right, starting from 0, plain adds)
#                    / float(box area)                       (fast approximate division again)
# An empty box sums to 0 and divides by its (zero or negative) area as it stands. The exact rounding of the
# divisions matters: the correctly rounded one is 1 ulp off on a fifth of the pixels.
#
# Usage: python gen_depth_down_ptx.py <out.ptx>
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("out")
a = ap.parse_args()

L = []


def w(s=""):
    L.append(s)


w("// GENERATED by tools/kernels/gen_depth_down_ptx.py - do not edit by hand.")
w("// numthreads 8 x 8 x 1; ftz")
w(".version 7.0")
w(".target sm_75")
w(".address_size 64")
w("")
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
w("    .param .align 16 .b8 p_s0[48],")
w("    .param .align 16 .b8 p_s32[48],")
w("    .param .align 16 .b8 p_cb0[32]")
w(") .reqntid 8, 8, 1")
w("{")
w("    .reg .pred %pt, %pa, %pb;")
w("    .reg .b32 %x, %y, %t0, %t1, %sx, %sy, %sw, %sh, %ow, %oh, %pad0, %pad1;")
w("    .reg .b32 %fx, %fy, %fow, %foh, %fsw, %fsh, %f0, %f1, %f2, %f3, %acc, %v, %v1, %v2, %v3;")
w("    .reg .b32 %xlo, %xhi, %ylo, %yhi, %i, %j, %ci, %cj, %area, %farea, %res;")
w("    .reg .b32 %wd, %ht, %dp, %esz, %pitch;")
w("    .reg .b64 %q0, %base, %addr64;")
w("")
w("    mov.u32 %t0, %ctaid.x;")
w("    mov.u32 %t1, %ntid.x;")
w("    mov.u32 %x, %tid.x;")
w("    mad.lo.s32 %x, %t0, %t1, %x;")
w("    mov.u32 %t0, %ctaid.y;")
w("    mov.u32 %t1, %ntid.y;")
w("    mov.u32 %y, %tid.y;")
w("    mad.lo.s32 %y, %t0, %t1, %y;")
w("    ld.param.v4.b32 {%sx, %sy, %sw, %sh}, [p_cb0+0];")
w("    ld.param.v4.b32 {%ow, %oh, %pad0, %pad1}, [p_cb0+16];")
w("    setp.hs.u32 %pa, %x, %ow;")
w("    setp.hs.or.u32 %pa, %y, %oh, %pa;")
w("    @%pa bra DONE;")
w("    cvt.rn.f32.u32 %fx, %x;")
w("    cvt.rn.f32.u32 %fy, %y;")
w("    cvt.rn.f32.u32 %fow, %ow;")
w("    cvt.rn.f32.u32 %foh, %oh;")
w("    cvt.rn.f32.u32 %fsw, %sw;")
w("    cvt.rn.f32.u32 %fsh, %sh;")


def bound(frac, f_pos, f_n, f_size, size, rnd, out, clampmin):
    """out = (clamp to size if clampmin) int(rnd(size * ((pos + frac) / n)))."""
    w(f"    add.rn.ftz.f32 %f0, {f_pos}, {frac};")
    w(f"    div.approx.ftz.f32 %f0, %f0, {f_n};")
    w(f"    mul.rn.ftz.f32 %f0, {f_size}, %f0;")
    w(f"    cvt.{rnd}.ftz.f32.f32 %f0, %f0;")
    w(f"    cvt.rzi.ftz.s32.f32 {out}, %f0;")
    if clampmin:
        w(f"    min.u32 {out}, {out}, {size};")


bound("0f3C23D70A", "%fx", "%fow", "%fsw", "%sw", "rmi", "%xlo", False)    # 0.01
bound("0f3F7D70A4", "%fx", "%fow", "%fsw", "%sw", "rpi", "%xhi", True)     # 0.99
bound("0f3C23D70A", "%fy", "%foh", "%fsh", "%sh", "rmi", "%ylo", False)
bound("0f3F7D70A4", "%fy", "%foh", "%fsh", "%sh", "rpi", "%yhi", True)
w("    ld.param.u64 %q0, [p_s0+40];")
w("    mov.b32 %acc, 0;")
w("    mov.b32 %j, %ylo;")
w("ROWS:")
w("    setp.ge.s32 %pa, %j, %yhi;")
w("    @%pa bra SUMDONE;")
w("    add.s32 %cj, %sy, %j;")
w("    mov.b32 %i, %xlo;")
w("COLS:")
w("    setp.ge.s32 %pb, %i, %xhi;")
w("    @%pb bra NEXTROW;")
w("    add.s32 %ci, %sx, %i;")
w("    tex.2d.v4.f32.s32 {%v, %v1, %v2, %v3}, [%q0, {%ci, %cj}];")
w("    add.rn.ftz.f32 %acc, %v, %acc;")
w("    add.s32 %i, %i, 1;")
w("    bra COLS;")
w("NEXTROW:")
w("    add.s32 %j, %j, 1;")
w("    bra ROWS;")
w("SUMDONE:")
w("    sub.s32 %t0, %xhi, %xlo;")
w("    sub.s32 %t1, %yhi, %ylo;")
w("    mul.lo.s32 %area, %t1, %t0;")
w("    cvt.rn.f32.s32 %farea, %area;")
w("    div.approx.ftz.f32 %res, %acc, %farea;")
w("    ld.param.u64 %base, [p_s32+0];")
w("    ld.param.u32 %wd, [p_s32+16];")
w("    ld.param.u32 %ht, [p_s32+20];")
w("    ld.param.u32 %dp, [p_s32+24];")
w("    ld.param.u32 %esz, [p_s32+28];")
w("    ld.param.u32 %pitch, [p_s32+36];")
w("    setp.lo.u32 %pt, %x, %wd;")
w("    setp.lo.and.u32 %pt, %y, %ht, %pt;")
w("    setp.lo.and.u32 %pt, 0, %dp, %pt;")
w("    mul.lo.s32 %t0, %y, %pitch;")
w("    mad.lo.s32 %t0, %x, %esz, %t0;")
w("    cvt.u64.u32 %addr64, %t0;")
w("    add.s64 %addr64, %base, %addr64;")
w("    @%pt st.global.b32 [%addr64], %res;")
w("DONE:")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
