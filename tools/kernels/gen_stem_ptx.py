# Emits our own kernel for the first layer of a flow network, in the pack's kernel interface
# (p_desc, 48-byte slots, the constant buffer by value in p_cb0): same slots, same grid (8 x 8 threads, one output
# pixel each, one group z of NCO output channels), same bytes as the module it replaces.
#
#   stem a   net A: 4 -> 128 channels (z: 8), stride 2, 3x3. The input is a texture of 2-byte texels (two int8
#            channels); the layer's four input channels are those two, the dispatch's scalar c11 and zero:
#            word = b0 | b1 << 8 | c11 << 16 (a tap outside the crop is the zero word, a texel outside the
#            texture has b0 = b1 = 0). Tap (ex, ey): x = 2 gx - 1 + ex - c6, y = 2 gy - 1 + ey - c7; outside
#            when x < 0, x >= c2 or y >= c3 (unsigned). Output: texel (gx, gy + 1) of slice z, 8 bytes.
#   stem b   net B: 8 -> 32 channels (z: 16), stride 2, 3x3. The input is two raw buffers: the flow, 8 channels
#            of half floats per pixel (pixel (x, y) at byte 2 c8 (c0 y + x); five are read, 16 bytes from that
#            offset when they lie inside the buffer, zero otherwise), and the warp, 4 bytes a pixel at 4 (c0 y + x).
#            The tap's two words are: warp & 0xFFFF | q0 << 16 | q1 << 24 and q2 | q3 << 8 | q4 << 16 | sb << 24
#            with q = clamp(trunc(half), -128, 127) as bytes and sb = (c11 & 127) | (c11 >> 31) << 7. Tap (ex, ey):
#            x = 2 gx - 1 + ex - c6, y = 2 gy + ey - c7; outside when x < 0, x >= c2, y == 0 or y >= c3 + 1.
#            Output: texel (gx, gy + 1) of slice z, 16 bytes.
# Both: acc[co] = s2[NCO z + co] + sum over taps, input channels of in * W (dp4a), then the requantisation of
# gen_s2_ptx.py (clamp to `bits`, the two-sided shifted multiply, clamp to int8). Weights (slot 1) of group z start at
# piece z * 18 (a) or z * 72 (b), 16 bytes a piece = four output channels of one tap and word: piece h * 9 + tap
# (a), h * 18 + 2 tap + word (b), h = the group of four output channels.
#
# Usage: python gen_stem_ptx.py <out.ptx> --stem a|b --bits N
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--stem", required=True, choices=("a", "b"))
ap.add_argument("--bits", type=int, required=True)
a = ap.parse_args()

B = a.stem == "b"
NH = 4 if B else 2             # groups of four output channels
NCO = 4 * NH
WORDS = 2 if B else 1          # dp4a words a tap
NP = NH * 9 * WORDS            # pieces a group
CMAX = (1 << (a.bits - 1)) - 1
L = []


def w(s=""):
    L.append(s)


w(f"// GENERATED by gen_stem_ptx.py --stem {a.stem} --bits {a.bits} - our own kernel for net {'B' if B else 'A'}'s first layer.")
w(".version 7.0")
w(".target sm_75")
w(".address_size 64")
w()
w(".visible .entry dxil_main(")
w("    .param .u64 p_desc,")
for s in ("s0", "s1", "s2", "s3") + (("s4",) if B else ()) + ("s32",):
    w(f"    .param .align 16 .b8 p_{s}[48],")
w("    .param .align 16 .b8 p_cb0[48]")
w(") .reqntid 8, 8, 1")
w("{")
w(f"    .shared .align 16 .b32 ws[{NP * 4}];")
w("    .reg .pred %p, %pz, %pa, %pb, %pc, %pd;")
w("    .reg .b32 %tl, %gx, %gy, %gz, %i, %j, %t, %u, %v, %sz, %idx;")
w("    .reg .b32 %cP, %cW, %cH, %cH1, %cLX, %cLY, %cCX, %cCY, %cMul, %cSh, %cS, %cB;")
w("    .reg .b32 %w0, %h0, %n0, %b0x, %pi0, %s2, %s3, %sz0, %sz4, %xx, %yy, %lin, %off, %al;")
w("    .reg .b32 %V0, %V1, %V2, %V3, %P0, %P1, %P2, %P3, %wb, %q0, %q1, %q2, %q3, %q4, %sb;")
w("    .reg .b32 " + ", ".join(f"%acc{k}" for k in range(NCO)) + ";")
w("    .reg .b32 %mp, %shp, %shn, %rp, %rn, %s, %e, %f, %o0, %o1, %o2, %o3, %pix, %wsb;")
w("    .reg .b32 %a0, %a1;")
w("    .reg .b16 %hh;")
w("    .reg .f32 %ff;")
w("    .reg .b64 %B0, %B1, %B2, %B3, %B4, %BO, %r64;")
w()
w("    mov.u32 %t, %tid.y;")
w("    mov.u32 %u, %tid.x;")
w("    mad.lo.u32 %tl, %t, 8, %u;")
w("    mov.u32 %gx, %ctaid.x;")
w("    mad.lo.u32 %gx, %gx, 8, %u;")
w("    mov.u32 %gy, %ctaid.y;")
w("    mad.lo.u32 %gy, %gy, 8, %t;")
w("    mov.u32 %gz, %ctaid.z;")
w("    ld.param.u32 %cP, [p_cb0+0];")
w("    ld.param.u32 %cW, [p_cb0+8];")
w("    ld.param.u32 %cH, [p_cb0+12];")
w("    ld.param.u32 %cLX, [p_cb0+16];")
w("    ld.param.u32 %cLY, [p_cb0+20];")
w("    ld.param.u32 %cCX, [p_cb0+24];")
w("    ld.param.u32 %cCY, [p_cb0+28];")
w("    ld.param.u32 %cB, [p_cb0+32];")
w("    ld.param.u32 %cMul, [p_cb0+36];")
w("    ld.param.u32 %cSh, [p_cb0+40];")
w("    ld.param.u32 %cS, [p_cb0+44];")
w("    add.s32 %cH1, %cH, 1;")
w("    ld.param.u64 %B1, [p_s1+0];")
w("    ld.param.u32 %sz, [p_s1+32];")
w(f"    // the group's weights into shared memory ({NP} pieces); a piece past the buffer is zero")
w(f"    mul.lo.u32 %idx, %gz, {NP};")
w("    mov.u32 %wsb, ws;")
for it in range((NP + 63) // 64):
    w(f"    add.u32 %i, %tl, {64 * it};")
    w(f"    setp.lt.u32 %pz, %i, {NP};")
    w("    add.u32 %j, %idx, %i;")
    w("    mul.lo.u32 %u, %j, 16;")
    w("    add.u32 %u, %u, 16;")
    w("    setp.le.and.u32 %p, %u, %sz, %pz;")
    for k in range(4):
        w(f"    mov.b32 %V{k}, 0;")
    w("    mul.wide.u32 %r64, %j, 16;")
    w("    add.s64 %r64, %B1, %r64;")
    w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%r64];")
    w("    mad.lo.u32 %u, %i, 16, %wsb;")
    w("    @%pz st.shared.v4.b32 [%u], {%V0, %V1, %V2, %V3};")
w()
w("    // the accumulators start at the bias: pieces NH z + h, each read only inside the buffer")
w("    ld.param.u64 %B2, [p_s2+0];")
w("    ld.param.u32 %s2, [p_s2+32];")
for h in range(NH):
    w(f"    mad.lo.u32 %t, %gz, {NH}, {h};")
    w("    mul.lo.u32 %u, %t, 16;")
    w("    add.u32 %v, %u, 16;")
    w("    setp.le.u32 %p, %v, %s2;")
    for k in range(4):
        w(f"    mov.b32 %acc{4 * h + k}, 0;")
    w("    cvt.u64.u32 %r64, %u;")
    w("    add.s64 %r64, %B2, %r64;")
    w(f"    @%p ld.global.nc.v4.b32 {{%acc{4 * h}, %acc{4 * h + 1}, %acc{4 * h + 2}, %acc{4 * h + 3}}}, [%r64];")
w("    ld.param.u64 %B0, [p_s0+0];")
if B:
    w("    ld.param.u32 %sz0, [p_s0+32];")
    w("    ld.param.u64 %B4, [p_s4+0];")
    w("    ld.param.u32 %sz4, [p_s4+32];")
    w("    // scalar byte")
    w("    and.b32 %sb, %cS, 127;")
    w("    shr.u32 %t, %cS, 31;")
    w("    shl.b32 %t, %t, 7;")
    w("    or.b32 %sb, %sb, %t;")
    w("    shl.b32 %sb, %sb, 24;")
else:
    w("    ld.param.u32 %w0, [p_s0+16];")
    w("    ld.param.u32 %h0, [p_s0+20];")
    w("    ld.param.u32 %n0, [p_s0+24];")
    w("    ld.param.u32 %b0x, [p_s0+28];")
    w("    ld.param.u32 %pi0, [p_s0+36];")
    w("    shl.b32 %cS, %cS, 16;")
w("    bar.sync 0;")
w()
for t in range(9):
    ex, ey = t % 3, t // 3
    w(f"    // tap {t}")
    w("    shl.b32 %xx, %gx, 1;")
    w(f"    add.s32 %xx, %xx, {ex - 1};")
    w("    sub.s32 %xx, %xx, %cCX;")
    w("    shl.b32 %yy, %gy, 1;")
    w(f"    add.s32 %yy, %yy, {ey - 1 + (1 if B else 0)};")
    w("    sub.s32 %yy, %yy, %cCY;")
    w("    setp.ge.s32 %pa, %xx, 0;")
    w("    setp.lo.and.u32 %pa, %xx, %cW, %pa;")
    if B:
        w("    setp.ne.and.s32 %pa, %yy, 0, %pa;")
        w("    setp.lo.and.u32 %pa, %yy, %cH1, %pa;")
        w("    mov.b32 %a0, 0;")
        w("    mov.b32 %a1, 0;")
        w(f"    @!%pa bra T{t}_DONE;")
        w("    mul.lo.s32 %lin, %cP, %yy;")
        w("    add.s32 %lin, %lin, %xx;")
        w("    shl.b32 %off, %cB, 1;")
        w("    mul.lo.s32 %off, %off, %lin;")
        w("    add.u32 %u, %off, 16;")
        w("    setp.le.u32 %pb, %u, %sz0;")
        w("    and.b32 %al, %off, 15;")
        w("    setp.eq.and.u32 %pc, %al, 0, %pb;")
        w("    setp.ne.and.u32 %pd, %al, 0, %pb;")
        w("    cvt.u64.u32 %r64, %off;")
        w("    add.s64 %r64, %B0, %r64;")
        for k in range(4):
            w(f"    mov.b32 %V{k}, 0;")
        w("    @%pc ld.global.nc.v4.u32 {%V0, %V1, %V2, %V3}, [%r64];")
        for k in range(4):
            w(f"    @%pd ld.global.nc.u32 %V{k}, [%r64+{4 * k}];")
        for q, (src, hi) in enumerate((("V0", 0), ("V0", 1), ("V1", 0), ("V1", 1), ("V2", 0))):
            if hi:
                w(f"    shr.u32 %t, %{src}, 16;")
            else:
                w(f"    and.b32 %t, %{src}, 65535;")
            w("    cvt.u16.u32 %hh, %t;")
            w("    cvt.f32.f16 %ff, %hh;")
            w(f"    cvt.rzi.ftz.s32.f32 %q{q}, %ff;")
            w(f"    max.s32 %q{q}, %q{q}, -128;")
            w(f"    min.s32 %q{q}, %q{q}, 127;")
            w(f"    and.b32 %q{q}, %q{q}, 255;")
        w("    shl.b32 %t, %lin, 2;")
        w("    add.u32 %u, %t, 4;")
        w("    setp.le.u32 %pb, %u, %sz4;")
        w("    cvt.u64.u32 %r64, %t;")
        w("    add.s64 %r64, %B4, %r64;")
        w("    mov.b32 %a0, 0;")
        w("    @%pb ld.global.nc.u32 %a0, [%r64];")
        w("    and.b32 %a0, %a0, 65535;")
        w("    shl.b32 %t, %q0, 16;")
        w("    or.b32 %a0, %a0, %t;")
        w("    shl.b32 %t, %q1, 24;")
        w("    or.b32 %a0, %a0, %t;")
        w("    shl.b32 %a1, %q3, 8;")
        w("    or.b32 %a1, %a1, %q2;")
        w("    shl.b32 %t, %q4, 16;")
        w("    or.b32 %a1, %a1, %t;")
        w("    or.b32 %a1, %a1, %sb;")
        w(f"T{t}_DONE:")
        words = ("%a0", "%a1")
    else:
        w("    setp.lo.and.u32 %pa, %yy, %cH, %pa;")
        w("    mov.b32 %a0, 0;")
        w("    setp.lo.and.u32 %pb, %xx, %w0, %pa;")
        w("    setp.lo.and.u32 %pb, %yy, %h0, %pb;")
        w("    setp.lo.and.u32 %pb, 0, %n0, %pb;")
        w("    mul.lo.u32 %u, %yy, %pi0;")
        w("    mad.lo.u32 %u, %xx, %b0x, %u;")
        w("    cvt.u64.u32 %r64, %u;")
        w("    add.s64 %r64, %B0, %r64;")
        w("    mov.b32 %t, 0;")
        w("    @%pb ld.global.nc.u16 %t, [%r64];")
        w("    bfe.s32 %a0, %t, 0, 8;")
        w("    and.b32 %a0, %a0, 255;")
        w("    bfe.s32 %t, %t, 8, 8;")
        w("    shl.b32 %t, %t, 8;")
        w("    and.b32 %t, %t, 65280;")
        w("    or.b32 %a0, %a0, %t;")
        w("    or.b32 %a0, %a0, %cS;")
        w("    selp.b32 %a0, %a0, 0, %pa;")
        words = ("%a0",)
    for wd, reg in enumerate(words):
        for h in range(NH):
            off = (h * 9 * WORDS + t * WORDS + wd) * 16
            w(f"    ld.shared.v4.b32 {{%P0, %P1, %P2, %P3}}, [%wsb+{off}];")
            for c in range(4):
                w(f"    dp4a.s32.s32 %acc{4 * h + c}, {reg}, %P{c}, %acc{4 * h + c};")
w()
w(f"    // epilogue: clamp to {a.bits} bits, the two-sided requantisation, clamp to int8")
w("    and.b32 %shp, %cSh, 31;")
w("    shr.u32 %shn, %cSh, 8;")
w("    add.u32 %t, %cSh, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rp, 1, %t;")
w("    add.u32 %t, %shn, 31;")
w("    and.b32 %t, %t, 31;")
w("    shl.b32 %rn, 1, %t;")
w("    and.b32 %shn, %shn, 31;")
w("    ld.param.u64 %B3, [p_s3+0];")
w("    ld.param.u32 %s3, [p_s3+32];")
w("    ld.param.u64 %BO, [p_s32+0];")
w("    ld.param.u32 %w0, [p_s32+16];")
w("    ld.param.u32 %h0, [p_s32+20];")
w("    ld.param.u32 %n0, [p_s32+24];")
w("    ld.param.u32 %b0x, [p_s32+28];")
w("    ld.param.u32 %pi0, [p_s32+36];")
w("    add.u32 %t, %gy, 1;")
w("    setp.lo.u32 %pa, %gx, %cLX;")
w("    setp.lo.and.u32 %pa, %gy, %cLY, %pa;")
w("    setp.lo.and.u32 %pa, %gx, %w0, %pa;")
w("    setp.lo.and.u32 %pa, %t, %h0, %pa;")
w("    setp.lo.and.u32 %pa, %gz, %n0, %pa;")
w("    mad.lo.u32 %pix, %gz, %h0, %t;")
w("    mul.lo.u32 %pix, %pix, %pi0;")
w("    mad.lo.u32 %pix, %gx, %b0x, %pix;")
w("    cvt.u64.u32 %r64, %pix;")
w("    add.s64 %BO, %BO, %r64;")
for h in range(NH):
    w(f"    mad.lo.u32 %t, %gz, {NH}, {h};")
    w("    mul.lo.u32 %u, %t, 16;")
    w("    add.u32 %v, %u, 16;")
    w("    setp.le.u32 %p, %v, %s3;")
    for k in range(4):
        w(f"    mov.b32 %V{k}, 0;")
    w("    cvt.u64.u32 %r64, %u;")
    w("    add.s64 %r64, %B3, %r64;")
    w("    @%p ld.global.nc.v4.b32 {%V0, %V1, %V2, %V3}, [%r64];")
    for c in range(4):
        w(f"    max.s32 %s, %acc{4 * h + c}, {-CMAX - 1};")
        w(f"    min.s32 %s, %s, {CMAX};")
        w("    max.s32 %e, %s, 0;")
        w("    mul.lo.s32 %e, %e, %cMul;")
        w("    add.s32 %e, %e, %rp;")
        w("    shr.s32 %e, %e, %shp;")
        w("    min.s32 %f, %s, 0;")
        w(f"    mul.lo.s32 %f, %f, %V{c};")
        w("    add.s32 %f, %f, %rn;")
        w("    shr.s32 %f, %f, %shn;")
        w("    add.s32 %e, %e, %f;")
        w("    max.s32 %e, %e, -128;")
        w("    min.s32 %e, %e, 127;")
        w("    and.b32 %e, %e, 255;")
        if c == 0:
            w(f"    mov.b32 %o{h}, %e;")
        else:
            w(f"    bfi.b32 %o{h}, %e, %o{h}, {8 * c}, 8;")
outs = ", ".join(f"%o{h}" for h in range(NH))
w(f"    @%pa st.global.v{NH}.b32 [%BO], {{{outs}}};")
w("    ret;")
w("}")

open(a.out, "w", newline="\n").write("\n".join(L) + "\n")
